def read_trimmed_file(path: Path) -> str:
    """Read a UTF-8 file and return stripped contents.

    Raises ``RuntimeError`` when the file is missing, unreadable, or empty
    after strip (exit path: prepare_run_context → exit 2).
    """
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise RuntimeError(f"cannot read {path}: {exc}") from exc
    stripped = text.strip()
    if not stripped:
        raise RuntimeError(f"file is empty: {path}")
    return stripped


def _extract_yaml_top_level(text: str, key: str) -> str | None:
    """Minimal top-level YAML ``key:`` extractor (no full YAML dependency).

    Supports plain scalars, single/double quotes, and ``|`` / ``>`` blocks.
    Only matches keys at column 0 (not nested mappings).
    """
    lines = text.splitlines()
    key_re = re.compile(rf"^{re.escape(key)}\s*:\s*(.*)$", re.IGNORECASE)
    i = 0
    while i < len(lines):
        match = key_re.match(lines[i])
        if match is None:
            i += 1
            continue
        rest = match.group(1).rstrip()
        rest_stripped = rest.strip()
        if rest_stripped in {"|", ">", "|-", "|+", ">-", ">+"} or rest_stripped.startswith(
            ("|", ">")
        ):
            block: list[str] = []
            i += 1
            while i < len(lines):
                line = lines[i]
                if line.strip() == "":
                    block.append("")
                    i += 1
                    continue
                if line[:1] in {" ", "\t"}:
                    block.append(line)
                    i += 1
                    continue
                break
            if not block:
                return None
            # Dedent by shortest leading indent among non-empty lines.
            indents = [
                len(ln) - len(ln.lstrip(" \t"))
                for ln in block
                if ln.strip()
            ]
            pad = min(indents) if indents else 0
            dedented = [
                ln[pad:] if len(ln) >= pad else ln for ln in block
            ]
            value = "\n".join(dedented).strip()
            return value or None
        if len(rest_stripped) >= 2 and (
            (rest_stripped[0] == rest_stripped[-1] == '"')
            or (rest_stripped[0] == rest_stripped[-1] == "'")
        ):
            return rest_stripped[1:-1].strip() or None
        return rest_stripped or None
    return None


def _extract_md_section(text: str, titles: tuple[str, ...]) -> str | None:
    """Return the body of the first matching AT1–H6 section title."""
    for title in titles:
        pattern = re.compile(
            rf"(?ims)^\s*#{{1,6}}\s*{re.escape(title)}\s*\n+(.*?)(?=^\s*#{{1,6}}\s|\Z)"
        )
        match = pattern.search(text)
        if match is None:
            continue
        body = match.group(1).strip()
        if body:
            return body
    return None


def parse_task_pack_text(text: str) -> tuple[str, str | None]:
    """Parse goal (+ optional acceptance) from task-pack YAML or Markdown text.

    YAML (minimal): top-level ``goal:`` / ``acceptance:``.
    Markdown: ``# Goal`` / ``## Goal`` and ``## Acceptance`` /
    ``## Acceptance criteria``. YAML keys win when ``goal:`` is present.
    """
    goal = _extract_yaml_top_level(text, "goal")
    acceptance = _extract_yaml_top_level(text, "acceptance")
    if goal and goal.strip():
        acc = acceptance.strip() if acceptance and acceptance.strip() else None
        return goal.strip(), acc
    goal_md = _extract_md_section(text, ("Goal",))
    acceptance_md = _extract_md_section(
        text, ("Acceptance criteria", "Acceptance")
    )
    if goal_md and goal_md.strip():
        acc = (
            acceptance_md.strip()
            if acceptance_md and acceptance_md.strip()
            else None
        )
        return goal_md.strip(), acc
    return "", None


def load_task_pack(path: Path) -> tuple[str, str | None]:
    """Load ``(goal, acceptance)`` from a YAML or Markdown task pack file.

    Raises ``RuntimeError`` when unreadable or goal is empty.
    """
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise RuntimeError(f"cannot read task pack {path}: {exc}") from exc
    goal, acceptance = parse_task_pack_text(raw)
    if not goal:
        raise RuntimeError(f"task pack has empty or missing goal: {path}")
    return goal, acceptance


def _optional_path(value: Any) -> Path | None:
    if value is None:
        return None
    if isinstance(value, Path):
        return value.expanduser()
    if isinstance(value, str) and value.strip():
        return Path(value.strip()).expanduser()
    return None


def resolve_goal_and_acceptance(
    args: argparse.Namespace,
    *,
    meta: dict[str, Any] | None = None,
    notes_dir: Path | None = None,
) -> tuple[str, str | None]:
    """Resolve overall goal and optional acceptance for this invocation.

    **Goal precedence** (first non-empty wins):
    1. CLI ``--goal``
    2. ``--goal-file`` contents
    3. ``--task-pack`` goal
    4. On ``--resume`` only: re-read meta ``goal_file`` / ``task_pack`` if
       present on disk; else ``run.json`` ``goal``; else ``NEEDS_OWNER`` Goal

    **Acceptance precedence**:
    1. ``--acceptance-file`` contents
    2. ``--task-pack`` acceptance (when pack is used this invocation)
    3. On ``--resume``: re-read meta ``acceptance_file`` / ``task_pack``;
       else ``run.json`` ``acceptance`` string

    Resume file-missing policy: if a meta path is set but the file is gone,
    fall back to stored ``goal`` / ``acceptance`` text in ``run.json`` (do not
    hard-fail solely because the source file moved). Still error when no goal
    string can be resolved at all.

    Side effects: sets ``args.goal``, ``args.acceptance``, and resolved path
    attributes ``goal_file`` / ``acceptance_file`` / ``task_pack`` (Path|None).
    """
    meta = meta or {}
    resume = bool(getattr(args, "resume", False))

    cli_goal = (getattr(args, "goal", None) or "").strip() or None
    goal_file = _optional_path(getattr(args, "goal_file", None))
    acceptance_file = _optional_path(getattr(args, "acceptance_file", None))
    task_pack = _optional_path(getattr(args, "task_pack", None))

    # On resume, restore paths from meta when CLI omitted them.
    if resume:
        if goal_file is None and isinstance(meta.get("goal_file"), str):
            goal_file = _optional_path(meta.get("goal_file"))
        if acceptance_file is None and isinstance(meta.get("acceptance_file"), str):
            acceptance_file = _optional_path(meta.get("acceptance_file"))
        if task_pack is None and isinstance(meta.get("task_pack"), str):
            task_pack = _optional_path(meta.get("task_pack"))

    pack_goal: str | None = None
    pack_acceptance: str | None = None
    if task_pack is not None:
        if task_pack.is_file():
            pack_goal, pack_acceptance = load_task_pack(task_pack)
        elif not resume:
            raise RuntimeError(f"--task-pack does not exist: {task_pack}")
        # resume + missing file: fall through to meta strings

    file_goal: str | None = None
    if goal_file is not None:
        if goal_file.is_file():
            file_goal = read_trimmed_file(goal_file)
        elif not resume:
            raise RuntimeError(f"--goal-file does not exist: {goal_file}")

    file_acceptance: str | None = None
    if acceptance_file is not None:
        if acceptance_file.is_file():
            file_acceptance = read_trimmed_file(acceptance_file)
        elif not resume:
            raise RuntimeError(
                f"--acceptance-file does not exist: {acceptance_file}"
            )

    # Goal: CLI > goal-file > task-pack > (resume meta / NEEDS_OWNER)
    goal = cli_goal or file_goal or pack_goal
    if goal is None and resume:
        meta_goal = meta.get("goal")
        if isinstance(meta_goal, str) and meta_goal.strip():
            goal = meta_goal.strip()
        if goal is None and notes_dir is not None:
            goal = parse_goal_from_needs_owner(notes_dir)

    # Acceptance: acceptance-file > task-pack > (resume meta text)
    acceptance = file_acceptance or pack_acceptance
    if acceptance is None and resume:
        meta_acc = meta.get("acceptance")
        if isinstance(meta_acc, str) and meta_acc.strip():
            acceptance = meta_acc.strip()

    if not goal:
        if resume:
            raise RuntimeError(
                "--resume: no goal; pass --goal / --goal-file / --task-pack "
                "or ensure run.json / NEEDS_OWNER.md contains one"
            )
        raise RuntimeError(
            "--goal is required unless --goal-file / --task-pack "
            "(or --resume with run.json / NEEDS_OWNER.md) provides one"
        )

    args.goal = goal
    args.acceptance = acceptance
    args.goal_file = goal_file.resolve() if goal_file is not None else None
    args.acceptance_file = (
        acceptance_file.resolve() if acceptance_file is not None else None
    )
    args.task_pack = task_pack.resolve() if task_pack is not None else None
    return goal, acceptance


def format_owner_reply_prefix(text: str) -> str:
    """Labeled block prepended to INSTRUCT/FIX when injecting owner clarification."""
    body = text.strip()
    return f"{OWNER_REPLY_HEADER}\n{body}\n\n"


def load_owner_reply_for_resume(
    notes_dir: Path,
    *,
    cli_owner_reply: str | None,
) -> str | None:
    """Resolve owner clarification for ``--resume``.

    Precedence: non-empty ``--owner-reply`` > non-empty ``OWNER_REPLY.md``.
    Whitespace-only values are ignored.
    """
    cli = (cli_owner_reply or "").strip()
    if cli:
        return cli
    path = notes_dir / OWNER_REPLY_NAME
    if not path.is_file():
        return None
    try:
        file_text = path.read_text(encoding="utf-8").strip()
    except OSError:
        return None
    return file_text or None


def should_inject_owner_reply(meta: dict[str, Any], text: str | None) -> bool:
    """True when *text* is non-empty and its digest is not already in *meta*."""
    if not text or not str(text).strip():
        return False
    stored = meta.get(OWNER_REPLY_META_KEY)
    if isinstance(stored, str) and stored == owner_reply_digest(text):
        return False
    return True


def mark_owner_reply_consumed(notes_dir: Path, text: str) -> None:
    """Persist consumption so a later ``--resume`` does not re-inject the same reply.

    Stores ``owner_reply_sha256`` in ``run.json`` (merged with existing keys) and
    renames ``OWNER_REPLY.md`` → ``OWNER_REPLY.consumed.md`` when the file is
    present. CLI-only replies still record the hash of the text that was injected.
    """
    ensure_notes_dir(notes_dir)
    digest = owner_reply_digest(text)
    meta = load_run_meta(notes_dir)
    meta[OWNER_REPLY_META_KEY] = digest
    path = notes_dir / RUN_META_NAME
    path.write_text(
        json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    reply_path = notes_dir / OWNER_REPLY_NAME
    if reply_path.is_file():
        consumed = notes_dir / OWNER_REPLY_CONSUMED_NAME
        reply_path.replace(consumed)


def is_turn_artifact_pending(path: Path) -> bool:
    """True when path is missing, empty, or only a write_skeleton placeholder."""
    if not path.exists():
        return True
    text = path.read_text(encoding="utf-8").strip()
    if not text:
        return True
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    if not lines:
        return True
    if any("_(pending)_" in ln for ln in lines) and len(lines) <= 2:
        return True
    return False


def parse_goal_from_needs_owner(notes_dir: Path) -> str | None:
    path = notes_dir / "NEEDS_OWNER.md"
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    match = re.search(
        r"(?ims)^\s*##\s*Goal\s*\n+(.*?)(?=^\s*##\s|\Z)",
        text,
    )
    if match is None:
        return None
    goal = match.group(1).strip()
    return goal or None


def load_run_meta(notes_dir: Path) -> dict[str, Any]:
    path = notes_dir / RUN_META_NAME
    if not path.exists():
        return {}
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return raw if isinstance(raw, dict) else {}


def _meta_str_list(raw: Any) -> list[str] | None:
    """Return a copy of *raw* when it is a list of strings, else ``None``."""
    if isinstance(raw, list) and all(isinstance(x, str) for x in raw):
        return list(raw)
    return None


def default_constraints_path() -> Path:
    """Absolute path to the bundled default constraints markdown file."""
    return Path(__file__).resolve().parent / DEFAULT_CONSTRAINTS_FILENAME


def resolve_notify_webhook(args: argparse.Namespace) -> str | None:
    """Resolve webhook URL: non-empty ``--notify-webhook`` beats env.

    Does not read ``run.json``; callers restore meta into ``args`` on resume
    before or after this helper (CLI/env still win when set).
    """
    cli = (getattr(args, "notify_webhook", None) or "").strip()
    if cli:
        return cli
    env = (os.environ.get(NOTIFY_WEBHOOK_ENV) or "").strip()
    return env or None


def notify_turns_webhook(
    url: str,
    *,
    event: str,
    goal: str,
    turn: int | None,
    verdict: str | None,
    stop_reason: str | None,
    notes_dir: Path,
    workdir: Path,
) -> None:
    """POST a terminal-state JSON payload to *url*; never raise to callers.

    Failures print a ``warning:`` line and return. Timeout
    ``NOTIFY_WEBHOOK_TIMEOUT_S`` seconds.
    """
    payload = {
        "event": event,
        "goal": goal,
        "turn": turn,
        "verdict": verdict,
        "stop_reason": stop_reason,
        "notes_dir": str(notes_dir.resolve()),
        "workdir": str(workdir.resolve()),
    }
    try:
        data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=data,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=NOTIFY_WEBHOOK_TIMEOUT_S):
            pass
    except Exception as err:  # noqa: BLE001 — must not fail the turns loop
        print(f"warning: notify webhook failed: {err}", flush=True)


def resolve_effective_constraints(
    args: argparse.Namespace,
) -> tuple[Path | None, bool]:
    """Return ``(constraints_path, use_default_constraints)`` for prompts.

    **Policy (always-on default mention, opt-out via flag):**

    - ``--constraints PATH`` → that file only; ``use_default=False``
    - ``--no-default-constraints`` (and no ``--constraints``) → ``None``;
      prompts keep the generic one-line guidance; ``use_default=False``
    - otherwise → bundled ``default_constraints_path()``; ``use_default=True``

    The default file is always shipped in-repo; users override with
    ``--constraints`` or disable mention with ``--no-default-constraints``.
    """
    cli_path = getattr(args, "constraints", None)
    if cli_path is not None:
        return Path(cli_path).expanduser().resolve(), False
    if bool(getattr(args, "no_default_constraints", False)):
        return None, False
    path = default_constraints_path()
    if not path.is_file():
        raise RuntimeError(f"bundled default constraints missing: {path}")
    return path, True


def write_run_meta(
    notes_dir: Path,
    *,
    goal: str,
    workdir: Path,
    max_turns: int,
    constraints: Path | None = None,
    use_default_constraints: bool | None = None,
    test_command: str | None = None,
    acceptance: str | None = None,
    goal_file: Path | None = None,
    acceptance_file: Path | None = None,
    task_pack: Path | None = None,
    planner_args: list[str] | None = None,
    coder_args: list[str] | None = None,
    reviewer_args: list[str] | None = None,
    notify_webhook: str | None = None,
) -> Path:
    """Write ``run.json``, preserving unknown keys from any existing file.

    Task-pack related keys: ``goal_file``, ``acceptance_file``, ``task_pack``
    (resolved paths), ``goal_sha256``, ``acceptance`` / ``acceptance_sha256``.
    Per-role nested argv: ``planner_args`` / ``coder_args`` / ``reviewer_args``.
    Constraints: ``constraints`` path + ``use_default_constraints`` bool.
    Notify: ``notify_webhook`` URL when set.
    """
    ensure_notes_dir(notes_dir)
    path = notes_dir / RUN_META_NAME
    payload: dict[str, Any] = dict(load_run_meta(notes_dir))
    payload["goal"] = goal
    payload["goal_sha256"] = content_digest(goal)
    payload["workdir"] = str(workdir.resolve())
    payload["max_turns"] = max_turns
    if constraints is not None:
        payload["constraints"] = str(constraints.resolve())
    else:
        payload.pop("constraints", None)
    if use_default_constraints is not None:
        payload["use_default_constraints"] = bool(use_default_constraints)
    if test_command is not None:
        payload["test_command"] = test_command
    if acceptance is not None and str(acceptance).strip():
        acc = str(acceptance).strip()
        payload["acceptance"] = acc
        payload["acceptance_sha256"] = content_digest(acc)
    else:
        payload.pop("acceptance", None)
        payload.pop("acceptance_sha256", None)
    if goal_file is not None:
        payload["goal_file"] = str(goal_file.resolve())
    if acceptance_file is not None:
        payload["acceptance_file"] = str(acceptance_file.resolve())
    if task_pack is not None:
        payload["task_pack"] = str(task_pack.resolve())
    if planner_args is not None:
        payload["planner_args"] = list(planner_args)
    if coder_args is not None:
        payload["coder_args"] = list(coder_args)
    if reviewer_args is not None:
        payload["reviewer_args"] = list(reviewer_args)
    if notify_webhook is not None and str(notify_webhook).strip():
        payload["notify_webhook"] = str(notify_webhook).strip()
    else:
        payload.pop("notify_webhook", None)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


def resolve_resume_start_turn(notes_dir: Path) -> int:
    """Return the absolute turn index to run next when ``--resume`` is set.

    Rules (checked in order):
    - Incomplete turn *n*: non-skeleton ``TURN{n}_PLAN`` or ``_RESULT`` exists,
      but ``TURN{n}_REVIEW`` is missing/skeleton → resume at *n*
      (covers crash mid-turn and planner ``STATUS: ESCALATE`` before fix).
    - Else next = last completed (non-skeleton) ``TURN{n}_REVIEW`` + 1.
    - If nothing found → 1.
    - If next > ``MAX_TURNS`` → raise ``RuntimeError``.
    """
    incomplete: list[int] = []
    completed_reviews: list[int] = []
    for n in range(1, MAX_TURNS + 1):
        plan = notes_dir / f"TURN{n}_PLAN.md"
        result = notes_dir / f"TURN{n}_RESULT.md"
        review = notes_dir / f"TURN{n}_REVIEW.md"
        plan_ready = not is_turn_artifact_pending(plan)
        result_ready = not is_turn_artifact_pending(result)
        review_ready = not is_turn_artifact_pending(review)
        if review_ready:
            completed_reviews.append(n)
        elif plan_ready or result_ready:
            incomplete.append(n)

    if incomplete:
        start = min(incomplete)
    elif completed_reviews:
        start = max(completed_reviews) + 1
    else:
        start = 1

    if start > MAX_TURNS:
        raise RuntimeError(
            f"--resume: next turn {start} exceeds hard cap MAX_TURNS={MAX_TURNS}"
        )
    return start


def archive_needs_owner(notes_dir: Path) -> Path | None:
    """Rename ``NEEDS_OWNER.md`` aside so a later escalate can rewrite it."""
    path = notes_dir / "NEEDS_OWNER.md"
    if not path.exists():
        return None
    archived = notes_dir / "NEEDS_OWNER.prev.md"
    path.replace(archived)
    return archived


def prepare_run_context(args: argparse.Namespace) -> tuple[Path, Path, Path | None, int, int]:
    """Validate CLI, resolve resume, return workdir/notes/constraints/start/end.

    Goal / acceptance resolution is delegated to
    ``resolve_goal_and_acceptance`` (CLI ``--goal`` always beats files;
    see that docstring for the full table and resume file-missing policy).
    ``--turns`` is the max turns for *this* invocation from ``start_turn``
    inclusive; absolute end is clamped to ``MAX_TURNS``.
    """
    err = validate_turns(args.turns)
    if err is not None:
        raise RuntimeError(err)

    owner_reply_cli = getattr(args, "owner_reply", None)
    if owner_reply_cli is not None and str(owner_reply_cli).strip() and not args.resume:
        raise RuntimeError("--owner-reply requires --resume")

    if args.resume:
        if args.notes_dir is None:
            raise RuntimeError("--resume requires --notes-dir")
        notes_dir = args.notes_dir.expanduser().resolve()
        if not notes_dir.is_dir():
            raise RuntimeError(f"--resume: notes-dir does not exist: {notes_dir}")
        if not any(notes_dir.iterdir()):
            raise RuntimeError(f"--resume: notes-dir is empty: {notes_dir}")

        meta = load_run_meta(notes_dir)
        resolve_goal_and_acceptance(args, meta=meta, notes_dir=notes_dir)

        if args.workdir is None and isinstance(meta.get("workdir"), str):
            args.workdir = Path(meta["workdir"])
        # Constraints preference: CLI --constraints / --no-default-constraints
        # win; else restore use_default_constraints / constraints from meta.
        # When meta says use_default=True, leave constraints unset so
        # resolve_effective_constraints re-binds the bundled path for this
        # checkout (do not pin a stale absolute path from another machine).
        cli_constraints = args.constraints is not None
        cli_no_default = bool(getattr(args, "no_default_constraints", False))
        if not cli_constraints and not cli_no_default:
            use_def = meta.get("use_default_constraints")
            if use_def is True:
                args.constraints = None
                args.no_default_constraints = False
            elif use_def is False:
                if isinstance(meta.get("constraints"), str):
                    args.constraints = Path(meta["constraints"])
                else:
                    args.no_default_constraints = True
            elif isinstance(meta.get("constraints"), str):
                # Legacy run.json without use_default_constraints.
                args.constraints = Path(meta["constraints"])
        # --test-command: CLI wins; else restore from run.json when omitted.
        cli_test = getattr(args, "test_command", None)
        if isinstance(cli_test, str) and cli_test.strip():
            args.test_command = cli_test.strip()
        else:
            meta_test = meta.get("test_command")
            if isinstance(meta_test, str) and meta_test.strip():
                args.test_command = meta_test.strip()
            else:
                args.test_command = None

        # Per-role agent argv: CLI wins; else restore resolved lists from meta.
        if getattr(args, "planner_args", None) is None:
            restored = _meta_str_list(meta.get("planner_args"))
            if restored is not None:
                args.planner_args = restored
        if getattr(args, "coder_args", None) is None:
            restored = _meta_str_list(meta.get("coder_args"))
            if restored is not None:
                args.coder_args = restored
        if getattr(args, "reviewer_args", None) is None:
            restored = _meta_str_list(meta.get("reviewer_args"))
            if restored is not None:
                args.reviewer_args = restored

        # notify webhook: CLI > env > run.json (same pattern as test_command).
        resolved_hook = resolve_notify_webhook(args)
        if resolved_hook:
            args.notify_webhook = resolved_hook
        else:
            meta_hook = meta.get("notify_webhook")
            if isinstance(meta_hook, str) and meta_hook.strip():
                args.notify_webhook = meta_hook.strip()
            else:
                args.notify_webhook = None

        start_turn = resolve_resume_start_turn(notes_dir)
    else:
        notes_dir = default_notes_dir(args)
        ensure_notes_dir(notes_dir)
        resolve_goal_and_acceptance(args, meta={}, notes_dir=notes_dir)
        start_turn = 1
        cli_test = getattr(args, "test_command", None)
        args.test_command = (
            cli_test.strip()
            if isinstance(cli_test, str) and cli_test.strip()
            else None
        )
        args.notify_webhook = resolve_notify_webhook(args)

    workdir = (args.workdir or Path.cwd()).resolve()
    constraints, use_default = resolve_effective_constraints(args)
    args.use_default_constraints = use_default
    # --turns = how many turns this invocation may run from start_turn.
    end_turn = min(start_turn + args.turns - 1, MAX_TURNS)
    if end_turn < start_turn:
        raise RuntimeError(
            f"--resume: no turns left to run (start_turn={start_turn}, "
            f"MAX_TURNS={MAX_TURNS})"
        )
    return workdir, notes_dir, constraints, start_turn, end_turn


_FIELD_RE_CACHE: dict[str, re.Pattern[str]] = {}


def extract_labeled_field(text: str | None, label: str) -> str | None:
    """Extract ``LABEL: value`` (value may span until the next ALLCAPS label)."""
    if not text:
        return None
    key = label.upper()
    pattern = _FIELD_RE_CACHE.get(key)
    if pattern is None:
        pattern = re.compile(
            rf"(?ims)^\s*{re.escape(key)}\s*:\s*(.+?)(?=^\s*[A-Z][A-Z0-9_]*\s*:|\Z)"
        )
        _FIELD_RE_CACHE[key] = pattern
    match = pattern.search(text)
    if match is None:
        return None
    value = " ".join(match.group(1).strip().split())
    return value or None


def summarize_body(text: str | None, *, limit: int = 240) -> str:
    if not text:
        return "_(なし)_"
    lines = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith("_("):
            continue
        if re.match(r"^(STATUS|TASK|DONE_WHEN|OUT_OF_SCOPE|DONE|VERIFIED|VERDICT|IMPROVE|EFFECT)\s*:", line, re.I):
            continue
        if line == "_(pending)_":
            continue
        lines.append(line)
    body = " ".join(lines).strip()
    if not body:
        return "_(記載なし)_"
    if len(body) > limit:
        return body[: limit - 1] + "…"
    return body


def turn_effect_rows(records: list[TurnRecord]) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for rec in records:
        plan = read_text(rec.plan_path)
        result = read_text(rec.result_path)
        review = read_text(rec.review_path)
        verdict = rec.verdict or parse_verdict(review) or "—"
        task = extract_labeled_field(plan, "TASK") or summarize_body(plan)
        done = extract_labeled_field(result, "DONE") or summarize_body(result)
        improve = extract_labeled_field(review, "IMPROVE") or summarize_body(review)
        effect = extract_labeled_field(review, "EFFECT") or "—"
        rows.append(
            {
                "turn": str(rec.number),
                "task": task,
                "done": done,
                "improve": improve,
                "verdict": verdict,
                "effect": effect,
            }
        )
    return rows


def judge_effectiveness(
    records: list[TurnRecord],
    *,
    max_turns: int,
    stop_reason: str | None,
) -> tuple[str, list[str]]:
    """Return (label, bullet reasons) for human effectiveness review."""
    if not records:
        return "効果なし", ["ターンが 1 回も完了していない"]

    verdicts = [(r.verdict or parse_verdict(read_text(r.review_path)) or "") for r in records]
    revise_n = sum(1 for v in verdicts if v == "REVISE")
    done_n = sum(1 for v in verdicts if v == "DONE")
    approve_n = sum(1 for v in verdicts if v == "APPROVE")
    escalate_n = sum(1 for v in verdicts if v == "ESCALATE")
    reasons: list[str] = [
        f"完了ターン: {len(records)} / 予定上限 {max_turns}（ハードキャップ {MAX_TURNS}）",
        (
            f"VERDICT 内訳: DONE={done_n}, APPROVE={approve_n}, "
            f"REVISE={revise_n}, ESCALATE={escalate_n}"
        ),
    ]
    if stop_reason:
        reasons.append(f"早期終了: {stop_reason}")

    if escalate_n > 0 or (stop_reason and "ESCALATE" in stop_reason.upper()):
        return "オーナー判断待ち", reasons + [
            "レビューまたは planner が ESCALATE を出した（人間の判断が必要）"
        ]
    if done_n > 0 or (stop_reason and "DONE" in stop_reason.upper()):
        return "目標達成の見込み", reasons + [
            "レビューまたは planner が DONE を出した（大元の指示を満たした判定）"
        ]
    if revise_n > 0 and approve_n == 0 and done_n == 0:
        return "改善停滞の疑い", reasons + [
            "REVISE が続く一方で APPROVE/DONE がなく、効果が出ていない可能性"
        ]
    if revise_n > 0 and approve_n + done_n > 0:
        return "部分改善（レビュー反映あり）", reasons + [
            "REVISE による指摘適用を含み、前進はあったがゴール完了は未確認"
        ]
    if approve_n > 0:
        if len(records) >= max_turns:
            return "部分改善（継続余地あり）", reasons + [
                "全ターン消化したが DONE 未達。APPROVE のみで追加改善の余地が残る"
            ]
        return "部分改善（継続余地あり）", reasons + [
            "APPROVE があり前進は確認できるが、大元の指示への DONE は未達"
        ]
    return "判定保留", reasons + [
        "VERDICT 情報不足。各ターンの DONE / IMPROVE / EFFECT 行を確認すること"
    ]


def self_improve_report_filename(when: datetime | None = None) -> str:
    """Return ``自己改善yyyymmddhhmmss.md`` for local wall time."""
    stamp = (when or datetime.now()).strftime("%Y%m%d%H%M%S")
    return f"自己改善{stamp}.md"


def write_and_display_summary(
    summary: str,
    *,
    workdir: Path,
    notes_dir: Path,
    when: datetime | None = None,
) -> Path:
    """Write SUMMARY.md, timestamped report under workdir, and print to stdout."""
    summary_path = notes_dir / "SUMMARY.md"
    summary_path.write_text(summary, encoding="utf-8")

    report_name = self_improve_report_filename(when)
    report_path = workdir / report_name
    report_path.write_text(summary, encoding="utf-8")
    # Keep a copy next to turn artifacts for the daemon log directory.
    notes_copy = notes_dir / report_name
    if notes_copy.resolve() != report_path.resolve():
        notes_copy.write_text(summary, encoding="utf-8")

    banner = (
        f"======== 自己改善サマリー（効果判定） ========\n"
        f"画面表示 + ファイル:\n"
        f"  {report_path}\n"
        f"  {summary_path}\n"
        f"=========================================="
    )
    print(banner, flush=True)
    print(summary, flush=True)
    print(f"======== wrote {report_path} ========", flush=True)
    return report_path


def render_summary(
    records: list[TurnRecord],
    *,
    goal: str,
    notes_dir: Path,
    max_turns: int,
    stop_reason: str | None,
) -> str:
    """Build a Japanese effectiveness report for humans."""
    label, reasons = judge_effectiveness(
        records, max_turns=max_turns, stop_reason=stop_reason
    )
    rows = turn_effect_rows(records)

    lines = [
        "# 自己改善レポート（効果判定）",
        "",
        "## 大元の指示",
        "",
        goal.strip() or "_(未設定)_",
        "",
        "## 効果判定",
        "",
        f"**判定: {label}**",
        "",
    ]
    for reason in reasons:
        lines.append(f"- {reason}")
    lines.extend(
        [
            "",
            f"Notes: `{notes_dir}`",
            "",
            "## ターン一覧",
            "",
            "| ターン | このターンの指示 | できたこと | レビューで改善させたこと | VERDICT | 効果 |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
    )
    for row in rows:
        lines.append(
            "| "
            + " | ".join(
                [
                    row["turn"],
                    _md_cell(row["task"]),
                    _md_cell(row["done"]),
                    _md_cell(row["improve"]),
                    row["verdict"],
                    _md_cell(row["effect"]),
                ]
            )
            + " |"
        )
    lines.append("")

    for rec in records:
        plan = read_text(rec.plan_path) or f"_(missing TURN{rec.number}_PLAN.md)_"
        result = read_text(rec.result_path) or f"_(missing TURN{rec.number}_RESULT.md)_"
        review = read_text(rec.review_path) or f"_(missing TURN{rec.number}_REVIEW.md)_"
        lines.extend(
            [
                f"## ターン {rec.number} 詳細",
                "",
                f"VERDICT: {rec.verdict or parse_verdict(review) or '—'}",
                "",
                "### 指示（PLAN）",
                "",
                plan.rstrip(),
                "",
                "### できたこと（RESULT）",
                "",
                result.rstrip(),
                "",
                "### レビューで改善させたこと（REVIEW）",
                "",
                review.rstrip(),
                "",
            ]
        )
        if rec.notes:
            lines.append("### ランナーメモ")
            lines.append("")
            for note in rec.notes:
                lines.append(f"- {note}")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _md_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def read_text(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return None


def herdr_run(
    herdr: str,
    args: list[str],
    *,
    env: dict[str, str | None] | None = None,
    allow_empty: bool = False,
) -> dict[str, Any] | None:
    """Run a herdr CLI command.

    Most commands print JSON. Quiet commands such as ``pane run`` print nothing
    on success — pass ``allow_empty=True`` for those.
    """
    cmd = [herdr, *args]
    run_env: dict[str, str] | None = None
    if env is not None:
        run_env = os.environ.copy()
        for key, value in env.items():
            if value is None:
                run_env.pop(key, None)
            else:
                run_env[key] = value
    proc = subprocess.run(
        cmd, capture_output=True, text=True, check=False, env=run_env
    )
    if proc.returncode != 0:
        err = (proc.stderr or proc.stdout or "").strip()
        raise RuntimeError(
            f"`{' '.join(cmd)}` exited {proc.returncode}"
            + (f": {err}" if err else "")
        )
    stdout = (proc.stdout or "").strip()
    if not stdout:
        if allow_empty:
            return None
        raise RuntimeError(f"`{' '.join(cmd)}` produced no JSON output")
    try:
        payload = json.loads(stdout)
    except json.JSONDecodeError as err:
        raise RuntimeError(f"invalid JSON from `{' '.join(cmd)}`: {err}") from err
    if not isinstance(payload, dict):
        raise RuntimeError(f"unexpected JSON payload from `{' '.join(cmd)}`")
    error = payload.get("error")
    if error is not None:
        if isinstance(error, dict):
            code = error.get("code") or "error"
            message = error.get("message") or error
            raise RuntimeError(f"herdr API error ({code}): {message}")
        raise RuntimeError(f"herdr API error: {error}")
    return payload


def herdr_json(
    herdr: str,
    args: list[str],
    *,
    env: dict[str, str | None] | None = None,
) -> dict[str, Any]:
    payload = herdr_run(herdr, args, env=env, allow_empty=False)
    assert payload is not None
    return payload


def agent_status(
    herdr: str,
    target: str,
    *,
    env: dict[str, str | None] | None = None,
) -> str:
    payload = herdr_json(herdr, ["agent", "get", target], env=env)
    agent = payload.get("result", {}).get("agent") or {}
    status = agent.get("agent_status")
    if not isinstance(status, str):
        raise RuntimeError(f"agent get {target}: missing agent_status")
    return status


def agent_focus(
    herdr: str,
    target: str,
    *,
    env: dict[str, str | None] | None = None,
) -> None:
    herdr_json(herdr, ["agent", "focus", target], env=env)


def agent_send_keys(
    herdr: str,
    target: str,
    *keys: str,
    env: dict[str, str | None] | None = None,
) -> None:
    herdr_json(herdr, ["agent", "send-keys", target, *keys], env=env)


def prepare_agent(
    herdr: str,
    target: str,
    *,
    env: dict[str, str | None] | None = None,
) -> None:
    try:
        agent_focus(herdr, target, env=env)
    except RuntimeError:
        pass
    try:
        agent_send_keys(herdr, target, "esc", env=env)
    except RuntimeError:
        pass
    time.sleep(0.4)
    try:
        agent_focus(herdr, target, env=env)
    except RuntimeError:
        pass


def prompt_and_wait(
    herdr: str,
    target: str,
    text: str,
    *,
    timeout_ms: int,
    poll_seconds: float = DEFAULT_POLL_SECONDS,
    env: dict[str, str | None] | None = None,
) -> None:
    """Submit without --wait, then poll until working settles to idle/done.

    Avoids agent_prompt_stalled from --wait's short activity window.
    """
    prepare_agent(herdr, target, env=env)
    herdr_json(herdr, ["agent", "prompt", target, text], env=env)
    deadline = time.monotonic() + (timeout_ms / 1000.0)
    saw_work = False
    idle_ticks = 0
    while time.monotonic() < deadline:
        status = agent_status(herdr, target, env=env)
        if status in {"working", "blocked"}:
            saw_work = True
            idle_ticks = 0
            if status == "blocked":
                try_auto_yes_for_target(herdr, target, env=env)
        elif status in {"idle", "done"}:
            if saw_work:
                prepare_agent(herdr, target, env=env)
                return
            idle_ticks += 1
            if idle_ticks == 8:
                try:
                    agent_send_keys(herdr, target, "enter", env=env)
                except RuntimeError:
                    pass
            if idle_ticks >= DEFAULT_IDLE_GRACE and not saw_work:
                prepare_agent(herdr, target, env=env)
                return
        time.sleep(poll_seconds)
    raise TimeoutError(
        f"timed out waiting for {target} after prompt "
        f"(saw_work={saw_work}, timeout_ms={timeout_ms})"
    )


