def run_turns(args: argparse.Namespace) -> int:
    try:
        workdir, notes_dir, constraints, start_turn, end_turn = prepare_run_context(
            args
        )
    except RuntimeError as err:
        print(str(err), file=sys.stderr)
        return 2

    # Fresh runs create notes; resume never wipes existing TURN* artifacts.
    ensure_notes_dir(notes_dir)

    if args.daemon and not args.dry_run:
        # Rebuild argv from sys.argv[1:] so flags stay faithful.
        return daemonize(sys.argv[1:], notes_dir=notes_dir)

    if wants_leader_hub(args):
        try:
            hub_route = resolve_leader_hub_route(args)
        except RuntimeError as err:
            print(str(err), file=sys.stderr)
            return 2
        if not args.resume:
            write_run_meta(
                notes_dir,
                goal=args.goal,
                workdir=workdir,
                max_turns=args.turns,
                constraints=constraints,
                use_default_constraints=bool(
                    getattr(args, "use_default_constraints", False)
                ),
                test_command=getattr(args, "test_command", None),
            )
        return run_leader_hub_turns(
            args,
            workdir=workdir,
            notes_dir=notes_dir,
            start_turn=start_turn,
            end_turn=end_turn,
            route=hub_route,
            cli_env=None,
        )

    owner_reply_inject: str | None = None
    resolved_test_command = getattr(args, "test_command", None)
    resolved_acceptance = getattr(args, "acceptance", None)
    resolved_notify_webhook = getattr(args, "notify_webhook", None)
    resolved_planner_args, resolved_coder_args, resolved_reviewer_args = (
        resolve_role_agent_args(args)
    )
    task_meta_kwargs = dict(
        acceptance=resolved_acceptance,
        goal_file=getattr(args, "goal_file", None),
        acceptance_file=getattr(args, "acceptance_file", None),
        task_pack=getattr(args, "task_pack", None),
        planner_args=resolved_planner_args,
        coder_args=resolved_coder_args,
        reviewer_args=resolved_reviewer_args,
        notify_webhook=resolved_notify_webhook,
    )
    use_default_constraints = bool(
        getattr(args, "use_default_constraints", False)
    )
    if not args.resume:
        write_run_meta(
            notes_dir,
            goal=args.goal,
            workdir=workdir,
            max_turns=args.turns,
            constraints=constraints,
            use_default_constraints=use_default_constraints,
            test_command=resolved_test_command,
            **task_meta_kwargs,
        )
    else:
        # Refresh metadata with resolved goal/workdir; keep prior max_turns if present.
        meta = load_run_meta(notes_dir)
        prior_max = meta.get("max_turns")
        write_run_meta(
            notes_dir,
            goal=args.goal,
            workdir=workdir,
            max_turns=int(prior_max) if isinstance(prior_max, int) else args.turns,
            constraints=constraints,
            use_default_constraints=use_default_constraints,
            test_command=resolved_test_command,
            **task_meta_kwargs,
        )
        archived = archive_needs_owner(notes_dir)
        if archived is not None:
            print(f"resume: archived {archived.name}", flush=True)
        # Owner clarification: inject once into first turn of this resume session.
        resolved_reply = load_owner_reply_for_resume(
            notes_dir,
            cli_owner_reply=getattr(args, "owner_reply", None),
        )
        if resolved_reply is not None and should_inject_owner_reply(
            load_run_meta(notes_dir), resolved_reply
        ):
            owner_reply_inject = resolved_reply
            mark_owner_reply_consumed(notes_dir, owner_reply_inject)
            print("resume: injecting owner clarification into first turn", flush=True)

    cli_env: dict[str, str | None] | None = None
    nested: NestedPair | None = None
    multiparty_route: MultipartyRoute | None = None
    try:
        if wants_manual_multiparty(args):
            multiparty_route = resolve_multiparty_route(args)
            planner, coder, reviewer = legacy_roles_from_multiparty(
                multiparty_route
            )
            print(
                "multiparty: participants="
                + ",".join(multiparty_route.participants)
                + " order="
                + "→".join(multiparty_route.order)
                + " (manual layout; no nest/split)",
                flush=True,
            )
        elif wants_nested_pair(args):
            if args.dry_run:
                planner, coder, reviewer = "director", "coder", "reviewer"
                print(
                    "dry-run: would nest a Herdr session, lay out 2x2, and start "
                    f"director/coder/reviewer (kind={args.kind})",
                    flush=True,
                )
            else:
                # Let the launcher agent finish before stealing a sibling pane.
                if os.environ.get("HERDR_PANE_ID"):
                    try:
                        launcher = resolve_from_here(args.herdr)
                        wait_until_idle(
                            args.herdr,
                            launcher,
                            grace_ms=args.daemon_idle_grace_ms,
                        )
                    except RuntimeError:
                        pass
                nested = spawn_nested_coder_reviewer(
                    args.herdr,
                    workdir=workdir,
                    kind=args.kind,
                    planner_args=resolved_planner_args,
                    coder_args=resolved_coder_args,
                    reviewer_args=resolved_reviewer_args,
                    notes_dir=notes_dir,
                )
                planner = args.planner or nested.planner
                coder = nested.coder
                reviewer = nested.reviewer
                cli_env = session_cli_env(nested.session)
                print(
                    f"nested session={nested.session} outer_pane={nested.outer_pane_id} "
                    f"director={nested.director} coder={nested.coder} "
                    f"reviewer={nested.reviewer} spare={nested.spare_pane_id} "
                    f"work_root={nested.work_root}",
                    flush=True,
                )
        else:
            planner, coder, reviewer = resolve_roles(args)
    except RuntimeError as err:
        print(str(err), file=sys.stderr)
        return 2

    session_turns = end_turn - start_turn + 1
    print(
        f"roles: planner={planner} coder={coder} reviewer={reviewer} "
        f"turns={session_turns} (absolute {start_turn}–{end_turn}) "
        f"notes={notes_dir}",
        flush=True,
    )
    if args.resume:
        print(
            f"resume: starting at turn {start_turn} "
            f"(--turns={args.turns} → end {end_turn})",
            flush=True,
        )

    if args.from_here and args.self and not args.dry_run:
        wait_until_idle(
            args.herdr,
            coder,
            grace_ms=args.daemon_idle_grace_ms,
            env=cli_env,
        )

    records: list[TurnRecord] = []
    stop_reason: str | None = None
    if args.resume:
        stop_reason = None  # filled only on early stop this session
    # COMPLETE.md only on goal-met success (DONE, or STOP+goal-met language).
    # Mutually exclusive with NEEDS_OWNER (ESCALATE / stall). See should_write_complete.
    complete_pending = False
    complete_turn: int | None = None
    complete_verdict: str | None = None
    # Webhook escalate event: true ESCALATE only (not stall → event=stop).
    escalate_notify = False
    prev_review_path: Path | None = None
    prev_result_path: Path | None = None
    if start_turn > 1:
        prev_review_path = notes_dir / f"TURN{start_turn - 1}_REVIEW.md"
        prev_result_path = notes_dir / f"TURN{start_turn - 1}_RESULT.md"
        if is_turn_artifact_pending(prev_review_path):
            prev_review_path = None
        if is_turn_artifact_pending(prev_result_path):
            prev_result_path = None
    exit_code = 0

    try:
        # --turns = max turns this invocation from start_turn (absolute end_turn).
        for turn in range(start_turn, end_turn + 1):
            plan_path = notes_dir / f"TURN{turn}_PLAN.md"
            result_path = notes_dir / f"TURN{turn}_RESULT.md"
            review_path = notes_dir / f"TURN{turn}_REVIEW.md"
            instruct_text = instruct_prompt(
                turn=turn,
                turns=end_turn,
                goal=args.goal,
                workdir=workdir,
                notes_dir=notes_dir,
                constraints=constraints,
                prev_review_path=prev_review_path,
                prev_result_path=prev_result_path,
                acceptance=resolved_acceptance,
            )
            fix_text = fix_prompt(
                turn=turn,
                turns=end_turn,
                goal=args.goal,
                workdir=workdir,
                notes_dir=notes_dir,
                constraints=constraints,
            )
            # Inject owner reply only on the first turn of this resume invocation.
            if owner_reply_inject is not None and turn == start_turn:
                prefix = format_owner_reply_prefix(owner_reply_inject)
                instruct_text = prefix + instruct_text
                fix_text = prefix + fix_text
            rec = TurnRecord(
                number=turn,
                instruct_prompt=instruct_text,
                fix_prompt=fix_text,
                review_prompt=review_prompt(
                    turn=turn,
                    turns=end_turn,
                    goal=args.goal,
                    workdir=workdir,
                    notes_dir=notes_dir,
                    acceptance=resolved_acceptance,
                ),
                apply_prompt=None,
                plan_path=plan_path,
                result_path=result_path,
                review_path=review_path,
            )
            write_skeleton(plan_path, f"Turn {turn} plan")
            write_skeleton(result_path, f"Turn {turn} result")
            write_skeleton(review_path, f"Turn {turn} review")

            print(f"======== TURN {turn}/{end_turn}: instruct ========", flush=True)
            if args.dry_run:
                print(rec.instruct_prompt)
                rec.notes.append("dry-run: skipped herdr calls")
                # Keep a pre-seeded plan (stall fixtures); otherwise write a
                # per-turn TASK so multi-turn dry-runs do not false-stall.
                if is_turn_artifact_pending(plan_path):
                    plan_path.write_text(
                        f"# Turn {turn} plan\n\n"
                        f"STATUS: CONTINUE\n"
                        f"TASK: dry-run placeholder turn {turn}\n"
                        f"DONE_WHEN: ok\n"
                        f"OUT_OF_SCOPE: none\n",
                        encoding="utf-8",
                    )
            else:
                prompt_and_wait(
                    args.herdr,
                    planner,
                    rec.instruct_prompt,
                    timeout_ms=args.timeout_ms,
                    env=cli_env,
                )

            plan_text = read_text(plan_path)
            if parse_plan_escalate(plan_text):
                rec.notes.append("planner STATUS: ESCALATE — ending before fix")
                records.append(rec)
                stop_reason = f"planner escalated at turn {turn}"
                escalate_notify = True
                write_needs_owner(
                    notes_dir,
                    goal=args.goal,
                    turn=turn,
                    why=escalate_why_excerpt(plan_text, *rec.notes),
                )
                break
            if parse_plan_stop(plan_text):
                rec.notes.append("planner STATUS: DONE/STOP — ending before fix")
                records.append(rec)
                stop_reason = f"planner stopped at turn {turn}"
                plan_kind = parse_plan_stop_kind(plan_text)
                if should_write_complete(
                    plan_status=plan_kind,
                    evidence_texts=(plan_text,),
                ):
                    complete_pending = True
                    complete_turn = turn
                    complete_verdict = f"planner {plan_kind}"
                break

            # Stall detection: continuing plan whose TASK matches the previous
            # turn's TASK (normalized) → ESCALATE for owner clarification; skip FIX.
            # Stall → NEEDS_OWNER only; never COMPLETE.md.
            if turn > 1:
                prev_plan_text = read_text(notes_dir / f"TURN{turn - 1}_PLAN.md")
                if plan_tasks_stall(plan_text, prev_plan_text):
                    task_disp = (
                        extract_labeled_field(plan_text, "TASK") or ""
                    ).strip()
                    rec.notes.append("stall: repeated TASK")
                    records.append(rec)
                    stop_reason = f"repeated TASK at turn {turn}"
                    write_needs_owner(
                        notes_dir,
                        goal=args.goal,
                        turn=turn,
                        why=(
                            f"Director replanned the same work as the previous "
                            f"turn (repeated TASK: {task_disp}). "
                            f"Owner should clarify direction or change the goal."
                        ),
                    )
                    break

            print(f"======== TURN {turn}/{end_turn}: fix ========", flush=True)
            if args.dry_run:
                print(rec.fix_prompt)
            else:
                prompt_and_wait(
                    args.herdr,
                    coder,
                    rec.fix_prompt,
                    timeout_ms=args.timeout_ms,
                    env=cli_env,
                )

            # Soft-gate: after FIX, if VERIFIED is skeleton/vague, re-prompt the
            # coder once (same turn). If still weak, prepend a note to REVIEW so
            # a soft APPROVE is less likely. At most one automatic re-ask per turn.
            weak_review_note = False
            if result_has_weak_verified(read_text(result_path)):
                reask = weak_verified_reprompt(
                    turn=turn,
                    turns=end_turn,
                    notes_dir=notes_dir,
                )
                rec.notes.append("weak-verified: re-asked once")
                print(
                    f"======== TURN {turn}/{end_turn}: "
                    f"fix (weak VERIFIED re-ask) ========",
                    flush=True,
                )
                if args.dry_run:
                    print(reask)
                else:
                    prompt_and_wait(
                        args.herdr,
                        coder,
                        reask,
                        timeout_ms=args.timeout_ms,
                        env=cli_env,
                    )
                if result_has_weak_verified(read_text(result_path)):
                    weak_review_note = True
                    rec.notes.append("weak-verified: still weak after re-ask")

            # After FIX (+ optional weak VERIFIED re-ask): collect review state
            # pack, persist TURN{n}_STATE.txt, inject into REVIEW (replaces the
            # standalone diff-summary prepend to avoid duplicate git stats).
            state_pack = collect_turn_review_pack(
                workdir,
                test_command=resolved_test_command,
            )
            state_path = write_turn_state_pack(notes_dir, turn, state_pack)
            rec.review_prompt = review_prompt(
                turn=turn,
                turns=end_turn,
                goal=args.goal,
                workdir=workdir,
                notes_dir=notes_dir,
                state_pack=state_pack,
                state_path=state_path,
                acceptance=resolved_acceptance,
            )
            if weak_review_note:
                rec.review_prompt = (
                    f"{WEAK_VERIFIED_REVIEW_NOTE}\n\n{rec.review_prompt}"
                )

            print(f"======== TURN {turn}/{end_turn}: review ========", flush=True)
            if args.dry_run:
                print(rec.review_prompt)
                # Preserve pre-seeded non-skeleton REVIEW (fixtures / DONE tests).
                if is_turn_artifact_pending(review_path):
                    review_path.write_text(
                        f"# Turn {turn} review\n\n"
                        f"VERDICT: APPROVE\n\nDry-run placeholder.\n",
                        encoding="utf-8",
                    )
            else:
                prompt_and_wait(
                    args.herdr,
                    reviewer,
                    rec.review_prompt,
                    timeout_ms=args.timeout_ms,
                    env=cli_env,
                )

            # Manual multiparty: prompt remaining agents in conversation order
            # (beyond planner/coder/reviewer) so 3–4 roles exchange in one turn.
            if multiparty_route is not None and len(multiparty_route.order) > 3:
                for step_index, agent in enumerate(multiparty_route.order):
                    if step_index < 3:
                        continue
                    handoff = multiparty_handoff_prompt(
                        turn=turn,
                        turns=end_turn,
                        agent=agent,
                        route=multiparty_route,
                        goal=args.goal,
                        workdir=workdir,
                        notes_dir=notes_dir,
                        step_index=step_index,
                    )
                    print(
                        f"======== TURN {turn}/{end_turn}: "
                        f"multiparty[{step_index}]={agent} ========",
                        flush=True,
                    )
                    if args.dry_run:
                        print(handoff)
                        rec.notes.append(f"dry-run multiparty handoff → {agent}")
                    else:
                        prompt_and_wait(
                            args.herdr,
                            agent,
                            handoff,
                            timeout_ms=args.timeout_ms,
                            env=cli_env,
                        )
                        rec.notes.append(f"multiparty handoff → {agent}")

            review_text = read_text(review_path)
            verdict, verdict_notes = resolve_review_verdict(review_text)
            rec.verdict = verdict
            rec.notes.extend(verdict_notes)

            if verdict == "REVISE":
                rec.apply_prompt = apply_prompt(
                    turn=turn,
                    turns=end_turn,
                    notes_dir=notes_dir,
                )
                print(f"======== TURN {turn}/{end_turn}: apply ========", flush=True)
                if args.dry_run:
                    print(rec.apply_prompt)
                else:
                    prompt_and_wait(
                        args.herdr,
                        coder,
                        rec.apply_prompt,
                        timeout_ms=args.timeout_ms,
                        env=cli_env,
                    )
            elif verdict in {"DONE", "STOP"}:
                rec.notes.append(f"review VERDICT: {verdict} — stopping loop")
                records.append(rec)
                stop_reason = f"reviewer verdict {verdict} at turn {turn}"
                if should_write_complete(
                    final_verdict=verdict,
                    evidence_texts=(review_text, plan_text),
                ):
                    complete_pending = True
                    complete_turn = turn
                    complete_verdict = verdict
                break
            elif verdict == "ESCALATE":
                # ESCALATE → NEEDS_OWNER only; never COMPLETE.md.
                rec.notes.append("review VERDICT: ESCALATE — stopping loop")
                records.append(rec)
                stop_reason = f"reviewer verdict ESCALATE at turn {turn}"
                escalate_notify = True
                write_needs_owner(
                    notes_dir,
                    goal=args.goal,
                    turn=turn,
                    why=escalate_why_excerpt(
                        review_text,
                        read_text(plan_path),
                        *rec.notes,
                    ),
                )
                break

            records.append(rec)
            prev_review_path = review_path
            prev_result_path = result_path

        summary_stop = stop_reason
        if args.resume and summary_stop is not None:
            summary_stop = f"resumed from turn {start_turn}; {summary_stop}"
        summary = render_summary(
            records,
            goal=args.goal,
            notes_dir=notes_dir,
            max_turns=session_turns,
            stop_reason=summary_stop,
        )
        report_path = write_and_display_summary(
            summary,
            workdir=workdir,
            notes_dir=notes_dir,
        )
        if complete_pending and complete_turn is not None and complete_verdict:
            write_complete_md(
                notes_dir,
                goal=args.goal,
                turn=complete_turn,
                stop_reason=summary_stop,
                final_verdict=complete_verdict,
                summary_path=notes_dir / "SUMMARY.md",
                report_path=report_path,
            )
        # Terminal webhook (optional): after summary / COMPLETE are settled.
        if resolved_notify_webhook:
            last = records[-1] if records else None
            if complete_pending:
                hook_event = "complete"
                hook_turn = complete_turn
                hook_verdict = complete_verdict
            elif escalate_notify:
                hook_event = "escalate"
                hook_turn = last.number if last is not None else None
                hook_verdict = (
                    last.verdict
                    if last is not None and last.verdict
                    else "ESCALATE"
                )
            else:
                hook_event = "stop"
                hook_turn = last.number if last is not None else None
                hook_verdict = last.verdict if last is not None else None
            notify_turns_webhook(
                resolved_notify_webhook,
                event=hook_event,
                goal=args.goal,
                turn=hook_turn,
                verdict=hook_verdict,
                stop_reason=summary_stop,
                notes_dir=notes_dir,
                workdir=workdir,
            )
        if nested is not None and not args.dry_run:
            try:
                deliver_summary_to_caller(
                    args.herdr,
                    summary,
                    report_path=report_path,
                    notes_dir=notes_dir,
                    timeout_ms=args.timeout_ms,
                )
            except (RuntimeError, TimeoutError) as err:
                print(f"warning: summary delivery failed: {err}", flush=True)
            if args.keep_nested:
                print(
                    f"nested session left running: {nested.session} "
                    f"(outer pane {nested.outer_pane_id})",
                    flush=True,
                )
    except (RuntimeError, TimeoutError) as err:
        print(f"error: {err}", file=sys.stderr)
        exit_code = 1
    finally:
        if (
            nested is not None
            and not args.dry_run
            and not args.keep_nested
        ):
            cleanup_nested_pair(args.herdr, nested)

    return exit_code


def parse_turn_init_names(raw: str) -> list[str]:
    """Parse ``boss,agent-a,agent-b`` into a unique name list (2–4).

    Raises ``ValueError`` with a CLI-oriented message on bad input.
    """
    text = (raw or "").strip()
    # Allow accidental leading slash command text.
    if text.lower().startswith("/turn-init"):
        text = text[len("/turn-init") :].strip()
        if text.startswith(":") or text.startswith("="):
            text = text[1:].strip()
    if not text:
        # Bare ``/turn-init`` → default leader + 3 reports.
        return list(DEFAULT_TURN_INIT_NAMES)
    names: list[str] = []
    seen: set[str] = set()
    for part in text.replace(" ", ",").split(","):
        name = part.strip()
        if not name:
            continue
        key = name.casefold()
        if key in seen:
            raise ValueError(f"turn-init duplicate name {name!r}")
        seen.add(key)
        names.append(name)
    if len(names) < MIN_PARTICIPANTS:
        raise ValueError(
            f"turn-init needs at least {MIN_PARTICIPANTS} names "
            f"(leader + reports; got {len(names)})"
        )
    if len(names) > MAX_PARTICIPANTS:
        raise ValueError(
            f"turn-init accepts at most {MAX_PARTICIPANTS} names "
            f"(leader + up to {MAX_HUB_WORKERS} reports; got {len(names)})"
        )
    return names


def pane_sort_key(pane: dict[str, Any]) -> tuple[int, int, str]:
    """Sort panes top-to-bottom, left-to-right by layout rect."""
    rect = pane.get("rect") if isinstance(pane.get("rect"), dict) else {}
    y = int(rect.get("y") or 0)
    x = int(rect.get("x") or 0)
    pane_id = str(pane.get("pane_id") or "")
    return (y, x, pane_id)


def list_current_tab_panes_visual(
    herdr: str,
    *,
    env: dict[str, str | None] | None = None,
) -> list[dict[str, Any]]:
    """Return current-tab panes ordered visually (top-left → bottom-right)."""
    payload = herdr_json(herdr, ["pane", "layout", "--current"], env=env)
    result = payload.get("result") if isinstance(payload, dict) else None
    layout = None
    if isinstance(result, dict):
        layout = result.get("layout") if isinstance(result.get("layout"), dict) else result
    if not isinstance(layout, dict):
        raise RuntimeError("pane layout: missing layout object")
    panes = layout.get("panes") or []
    if not isinstance(panes, list) or not panes:
        raise RuntimeError("pane layout: no panes in the current tab")
    ordered = [p for p in panes if isinstance(p, dict) and p.get("pane_id")]
    ordered.sort(key=pane_sort_key)
    return ordered


def pane_display_label(pane: dict[str, Any]) -> str | None:
    """Return a non-empty pane label, or None."""
    label = pane.get("label")
    if isinstance(label, str) and label.strip():
        return label.strip()
    return None


def hub_target_name(
    *,
    agent_name: str | None,
    pane_label: str | None,
) -> str | None:
    """Prefer live agent name; fall back to pane label (pane→agent bind)."""
    if isinstance(agent_name, str) and agent_name.strip():
        return agent_name.strip()
    if isinstance(pane_label, str) and pane_label.strip():
        return pane_label.strip()
    return None


def list_pane_labels_by_id(
    herdr: str,
    pane_ids: list[str],
    *,
    env: dict[str, str | None] | None = None,
) -> dict[str, str]:
    """Map pane_id → label for panes that have a non-empty label."""
    wanted = {pid for pid in pane_ids if pid}
    if not wanted:
        return {}
    payload = herdr_json(herdr, ["pane", "list"], env=env)
    panes = (
        payload.get("result", {}).get("panes")
        or payload.get("panes")
        or []
    )
    out: dict[str, str] = {}
    for pane in panes:
        if not isinstance(pane, dict):
            continue
        pid = str(pane.get("pane_id") or "").strip()
        if pid not in wanted:
            continue
        label = pane_display_label(pane)
        if label:
            out[pid] = label
    return out


def try_agent_rename(
    herdr: str,
    pane_id: str,
    name: str,
    *,
    env: dict[str, str | None] | None = None,
) -> bool:
    """Best-effort ``agent rename``; return True on success.

    ``agent_not_found`` (empty shell / no agent yet) is quiet and returns False.
    Other failures print a warning and return False.
    """
    try:
        herdr_json(herdr, ["agent", "rename", pane_id, name], env=env)
        return True
    except RuntimeError as err:
        if "agent_not_found" not in str(err):
            print(
                f"warning: agent rename {pane_id} → {name}: {err}",
                flush=True,
            )
        return False


def bind_pane_labels_to_agents(
    herdr: str,
    *,
    env: dict[str, str | None] | None = None,
) -> list[tuple[str, str]]:
    """Align live agent names to pane labels (visual order).

    For each current-tab pane that has a label and a live agent whose name
    differs (or is empty), attempt ``agent rename`` to the label. Returns the
    list of ``(pane_id, label)`` pairs that were renamed successfully.
    """
    panes = list_current_tab_panes_visual(herdr, env=env)
    pane_ids = [str(p.get("pane_id")) for p in panes]
    labels = list_pane_labels_by_id(herdr, pane_ids, env=env)
    if not labels:
        return []
    payload = herdr_json(herdr, ["agent", "list"], env=env)
    agents = (
        payload.get("result", {}).get("agents")
        or payload.get("agents")
        or []
    )
    agent_name_by_pane: dict[str, str] = {}
    live_panes: set[str] = set()
    for agent in agents:
        if not isinstance(agent, dict):
            continue
        pid = str(agent.get("pane_id") or "").strip()
        if pid not in pane_ids:
            continue
        live_panes.add(pid)
        name = agent.get("name")
        if isinstance(name, str) and name.strip():
            agent_name_by_pane[pid] = name.strip()
    bound: list[tuple[str, str]] = []
    for pid in pane_ids:
        label = labels.get(pid)
        if not label or pid not in live_panes:
            continue
        current = agent_name_by_pane.get(pid)
        if current == label:
            continue
        if try_agent_rename(herdr, pid, label, env=env):
            bound.append((pid, label))
    return bound


def require_turn_init_single_pane(panes: list[dict[str, Any]]) -> str:
    """Require exactly one pane in the current tab; return its pane_id.

    ``turn-init`` / ``/turn-init`` may only start from a single-pane tab; it
    then splits to match the name count.
    """
    if len(panes) != 1:
        raise ValueError(
            "turn-init is only allowed when the current tab has a single pane "
            f"(found {len(panes)}). Use a fresh tab or close/merge extras first."
        )
    pane_id = str(panes[0].get("pane_id") or "").strip()
    if not pane_id:
        raise ValueError("turn-init: layout pane missing pane_id")
    return pane_id


def split_pane(
    herdr: str,
    pane_id: str,
    direction: str,
    *,
    env: dict[str, str | None] | None = None,
) -> str:
    """Split *pane_id* and return the new pane id."""
    payload = herdr_json(
        herdr,
        [
            "pane",
            "split",
            "--pane",
            pane_id,
            "--direction",
            direction,
            "--no-focus",
        ],
        env=env,
    )
    result = payload.get("result") if isinstance(payload, dict) else None
    pane = result.get("pane") if isinstance(result, dict) else None
    new_id = pane.get("pane_id") if isinstance(pane, dict) else None
    if not isinstance(new_id, str) or not new_id.strip():
        raise RuntimeError(
            f"pane split {pane_id} {direction}: missing result.pane.pane_id"
        )
    return new_id.strip()


def split_tab_for_turn_init(
    herdr: str,
    root_pane_id: str,
    pane_count: int,
    *,
    env: dict[str, str | None] | None = None,
) -> None:
    """Grow a single-pane tab into *pane_count* panes (2–4).

    Layouts:
    - 2: left | right
    - 3: top-left / bottom-left | right
    - 4: 2x2 (right, then down on left, then down on right)
    """
    if pane_count < 2:
        return
    if pane_count > MAX_PARTICIPANTS:
        raise ValueError(
            f"turn-init cannot split into {pane_count} panes "
            f"(max {MAX_PARTICIPANTS})"
        )
    right = split_pane(herdr, root_pane_id, "right", env=env)
    if pane_count == 2:
        return
    split_pane(herdr, root_pane_id, "down", env=env)
    if pane_count == 3:
        return
    # pane_count == 4
    split_pane(herdr, right, "down", env=env)


def build_turn_init_assignments(
    panes: list[dict[str, Any]], names: list[str]
) -> list[tuple[str, str]]:
    """Pair visual panes with turn-init names (pane_id, name).

    Requires exactly ``len(names)`` panes after splitting.
    """
    if len(panes) != len(names):
        raise ValueError(
            f"turn-init expected {len(names)} panes after split "
            f"(found {len(panes)})"
        )
    out: list[tuple[str, str]] = []
    for pane, name in zip(panes, names, strict=True):
        pane_id = str(pane.get("pane_id") or "").strip()
        if not pane_id:
            raise ValueError("turn-init: layout pane missing pane_id")
        out.append((pane_id, name))
    return out


def format_turn_init_launch_hint(names: list[str]) -> str:
    """Suggested ``herdr-turns --leader …`` line after a successful init."""
    leader, *reports = names
    parts = [
        "herdr-turns",
        f"--leader {leader}",
    ]
    for report in reports:
        parts.append(f"--participant {report}")
    parts.extend(
        [
            "--turns 3",
            '--goal "YOUR_GOAL"',
            "--notes-dir ./hub-notes",
            '--workdir "$PWD"',
        ]
    )
    return " ".join(parts)


def run_turn_init(
    *,
    herdr: str,
    names_raw: str,
    dry_run: bool = False,
    env: dict[str, str | None] | None = None,
) -> int:
    """From a single-pane tab: split to N panes, then name leader+reports."""
    try:
        names = parse_turn_init_names(names_raw)
        panes = list_current_tab_panes_visual(herdr, env=env)
        root_pane_id = require_turn_init_single_pane(panes)
    except ValueError as err:
        print(str(err), file=sys.stderr)
        return 2
    except RuntimeError as err:
        print(str(err), file=sys.stderr)
        return 1

    print(
        f"turn-init: single-pane ok ({root_pane_id}); "
        f"leader={names[0]} reports={','.join(names[1:])} "
        f"(roles not fixed; will split to {len(names)} panes)",
        flush=True,
    )
    if dry_run:
        print(
            f"dry-run: would split into {len(names)} panes then rename "
            + ", ".join(names),
            flush=True,
        )
        print("next:", format_turn_init_launch_hint(names), flush=True)
        return 0

    try:
        split_tab_for_turn_init(herdr, root_pane_id, len(names), env=env)
        panes = list_current_tab_panes_visual(herdr, env=env)
        assignments = build_turn_init_assignments(panes, names)
    except (RuntimeError, ValueError) as err:
        print(str(err), file=sys.stderr)
        return 1

    for pane_id, name in assignments:
        print(f"  {pane_id} → {name}", flush=True)
        # Pane labels work on empty shells; agent rename only when an agent exists.
        try:
            herdr_run(
                herdr,
                ["pane", "rename", pane_id, name],
                env=env,
                allow_empty=True,
            )
        except RuntimeError as err:
            print(
                f"error: failed to pane-rename {pane_id} → {name}: {err}",
                file=sys.stderr,
            )
            return 1
        # Empty panes after split have no agent yet — pane label is enough;
        # /turn-run re-binds live agents to labels via bind_pane_labels_to_agents.
        try_agent_rename(herdr, pane_id, name, env=env)
    print("next:", format_turn_init_launch_hint(names), flush=True)
    print(
        "hint: start agents with the pane label as NAME "
        "(`herdr agent start <label> --kind … --pane <pane>`), "
        "or let /turn-run bind labels→agent names automatically",
        flush=True,
    )
    return 0


def extract_turn_init_argv(argv: list[str]) -> tuple[str, bool] | None:
    """Detect ``turn-init`` / ``/turn-init`` invocation; return (names, dry_run).

    Accepted forms:

    - ``turn-init boss,a,b,c``
    - ``/turn-init boss,a,b,c``
    - ``/turn-init=boss,a,b,c``
    - ``turn-init --dry-run boss,a,b``
    """
    if not argv:
        return None
    first = argv[0]
    dry_run = False
    rest = argv[1:]
    if first in {"turn-init", "/turn-init"}:
        names_parts: list[str] = []
        for item in rest:
            if item in {"--dry-run", "-n"}:
                dry_run = True
                continue
            names_parts.append(item)
        return (" ".join(names_parts).strip(), dry_run)
    if first.startswith("/turn-init=") or first.startswith("turn-init="):
        raw = first.split("=", 1)[1]
        for item in rest:
            if item in {"--dry-run", "-n"}:
                dry_run = True
            else:
                raw = f"{raw} {item}"
        return (raw.strip(), dry_run)
    if first.startswith("/turn-init"):
        # "/turn-init boss,a" as a single argv occasionally
        rem = first[len("/turn-init") :].lstrip(" :=")
        if rem:
            for item in rest:
                if item in {"--dry-run", "-n"}:
                    dry_run = True
                else:
                    rem = f"{rem} {item}"
            return (rem.strip(), dry_run)
    return None



def parse_turn_run_spec(raw: str) -> tuple[int, str]:
    """Parse ``3,"goal text"`` / ``3,goal`` into ``(turns, goal)``.

    Accepts an optional ``/turn-run`` or ``turn-run`` prefix in *raw*.
    """
    text = (raw or "").strip()
    lower = text.lower()
    for prefix in ("/turn-run", "turn-run"):
        if lower.startswith(prefix):
            text = text[len(prefix) :].strip()
            if text[:1] in {":", "="}:
                text = text[1:].strip()
            break
    if not text:
        raise ValueError(
            'turn-run requires TURNS,"goal" — e.g. /turn-run 3,"ship the feature"'
        )
    match = re.match(
        r"""^(\d+)\s*[, ]\s*(?:"([^"]*)"|'([^']*)'|(.*))\s*$""",
        text,
        flags=re.DOTALL,
    )
    if match is None:
        raise ValueError(
            'turn-run could not parse TURNS,"goal" from '
            f"{raw!r} (example: 3,\"improve docs\")"
        )
    turns = int(match.group(1))
    goal = (match.group(2) or match.group(3) or match.group(4) or "").strip()
    err = validate_turns(turns)
    if err is not None:
        raise ValueError(err.replace("--turns", "turn-run turns"))
    if not goal:
        raise ValueError("turn-run goal must be non-empty")
    return turns, goal


def extract_turn_run_argv(
    argv: list[str],
) -> tuple[str, bool, Path | None] | None:
    """Detect ``turn-run`` / ``/turn-run``; return (spec, dry_run, notes_dir).

    Spec is the raw ``3,"goal"`` string (possibly including the slash command
    when packed into argv[0]).
    """
    if not argv:
        return None
    first = argv[0]
    dry_run = False
    notes_dir: Path | None = None
    rest = list(argv[1:])

    def _consume_flags(items: list[str]) -> list[str]:
        nonlocal dry_run, notes_dir
        out: list[str] = []
        i = 0
        while i < len(items):
            item = items[i]
            if item in {"--dry-run", "-n"}:
                dry_run = True
                i += 1
                continue
            if item == "--notes-dir" and i + 1 < len(items):
                notes_dir = Path(items[i + 1])
                i += 2
                continue
            if item.startswith("--notes-dir="):
                notes_dir = Path(item.split("=", 1)[1])
                i += 1
                continue
            out.append(item)
            i += 1
        return out

    if first in {"turn-run", "/turn-run"}:
        rest = _consume_flags(rest)
        return (" ".join(rest).strip(), dry_run, notes_dir)
    if first.startswith("/turn-run=") or first.startswith("turn-run="):
        raw = first.split("=", 1)[1]
        rest = _consume_flags(rest)
        if rest:
            raw = f"{raw} {' '.join(rest)}"
        return (raw.strip(), dry_run, notes_dir)
    if first.startswith("/turn-run") or first.startswith("turn-run"):
        # "/turn-run 3,\"goal\"" packed in argv[0], or "/turn-run3,..." 
        if first.lower().startswith("/turn-run"):
            rem = first[len("/turn-run") :]
        else:
            rem = first[len("turn-run") :]
        rem = rem.lstrip(" :=")
        rest = _consume_flags(rest)
        if rem:
            raw = rem if not rest else f"{rem} {' '.join(rest)}"
        else:
            raw = " ".join(rest)
        if raw.strip():
            return (raw.strip(), dry_run, notes_dir)
    return None


def resolve_hub_targets_from_current_tab(
    herdr: str,
    *,
    env: dict[str, str | None] | None = None,
) -> tuple[str, list[str]]:
    """Return ``(leader_name, report_names)`` from the current tab.

    Leader is the hub target for ``HERDR_PANE_ID``. Reports are other hub
    targets in the same tab, ordered top-left → bottom-right.

    Name resolution prefers a live agent name, then falls back to the pane
    label (so ``turn-init`` pane renames work even before / without agent
    rename). Prefer running ``bind_pane_labels_to_agents`` first when agents
    are already live.
    """
    pane_id = os.environ.get("HERDR_PANE_ID", "").strip()
    if not pane_id:
        raise RuntimeError(
            "turn-run must run inside a Herdr-managed pane "
            "(missing HERDR_PANE_ID). Focus the leader pane and retry."
        )
    panes = list_current_tab_panes_visual(herdr, env=env)
    pane_ids = [str(p.get("pane_id")) for p in panes]
    payload = herdr_json(herdr, ["agent", "list"], env=env)
    agents = (
        payload.get("result", {}).get("agents")
        or payload.get("agents")
        or []
    )
    agent_name_by_pane: dict[str, str] = {}
    for agent in agents:
        if not isinstance(agent, dict):
            continue
        pid = str(agent.get("pane_id") or "").strip()
        if pid not in pane_ids:
            continue
        name = agent.get("name")
        if isinstance(name, str) and name.strip():
            agent_name_by_pane[pid] = name.strip()
    labels_by_pane = list_pane_labels_by_id(herdr, pane_ids, env=env)
    named_by_pane: dict[str, str] = {}
    for pid in pane_ids:
        name = hub_target_name(
            agent_name=agent_name_by_pane.get(pid),
            pane_label=labels_by_pane.get(pid),
        )
        if name:
            named_by_pane[pid] = name
    if pane_id not in pane_ids:
        raise RuntimeError(
            f"turn-run: current pane {pane_id} is not in the current tab layout"
        )
    leader = named_by_pane.get(pane_id)
    if not leader:
        raise RuntimeError(
            f"turn-run: pane {pane_id} has no agent name or pane label — "
            "run `herdr-turns turn-init leader,report1,...` first"
        )
    reports: list[str] = []
    for pid in pane_ids:
        if pid == pane_id:
            continue
        name = named_by_pane.get(pid)
        if name:
            reports.append(name)
    if not reports:
        raise RuntimeError(
            "turn-run: no other named agents or labeled panes in this tab — "
            "split panes, turn-init (labels), then start agents"
        )
    if len(reports) > MAX_HUB_WORKERS:
        raise RuntimeError(
            f"turn-run: at most {MAX_HUB_WORKERS} reports under a leader "
            f"(found {len(reports)}: {', '.join(reports)})"
        )
    return leader, reports


def build_turn_run_argv(
    *,
    leader: str,
    reports: list[str],
    turns: int,
    goal: str,
    workdir: Path,
    notes_dir: Path,
    daemon: bool = True,
) -> list[str]:
    """Build ``herdr_agent_turns.py`` argv for leader-hub mode."""
    argv: list[str] = [
        "--leader",
        leader,
    ]
    for report in reports:
        argv.extend(["--participant", report])
    argv.extend(
        [
            "--turns",
            str(turns),
            "--goal",
            goal,
            "--notes-dir",
            str(notes_dir),
            "--workdir",
            str(workdir),
        ]
    )
    if daemon:
        argv.append("--daemon")
    return argv


def run_turn_run(
    *,
    herdr: str,
    spec_raw: str,
    dry_run: bool = False,
    notes_dir: Path | None = None,
    env: dict[str, str | None] | None = None,
) -> int:
    """Start leader-hub turns from the current (leader) pane."""
    try:
        turns, goal = parse_turn_run_spec(spec_raw)
        # After agents start on labeled panes, align agent names to labels.
        bound = bind_pane_labels_to_agents(herdr, env=env)
        for pane_id, label in bound:
            print(f"turn-run: bound agent on {pane_id} → {label}", flush=True)
        leader, reports = resolve_hub_targets_from_current_tab(herdr, env=env)
    except (ValueError, RuntimeError) as err:
        print(str(err), file=sys.stderr)
        return 2 if isinstance(err, ValueError) else 1

    workdir = Path.cwd().resolve()
    resolved_notes = (
        notes_dir.expanduser().resolve()
        if notes_dir is not None
        else (workdir / "hub-notes").resolve()
    )
    argv = build_turn_run_argv(
        leader=leader,
        reports=reports,
        turns=turns,
        goal=goal,
        workdir=workdir,
        notes_dir=resolved_notes,
        daemon=not dry_run,
    )
    print(
        "turn-run: leader="
        + leader
        + " reports="
        + ",".join(reports)
        + f" turns={turns}"
        + f" notes_dir={resolved_notes}",
        flush=True,
    )
    print("turn-run argv: herdr-turns " + " ".join(argv), flush=True)
    if dry_run:
        return 0
    # Re-enter main without the turn-run subcommand (daemon path).
    return main(argv)



# --- /auto-yes: toggle watcher that confirms Yes/proceed prompts ------------

AUTO_YES_HINT_RE = re.compile(
    r"(?is)(?:"
    r"do you want to proceed|"
    r"parser skipped input|"
    r"would you like to|"
    r"allow (?:this|the)|"
    r"approve (?:this|the)|"
    r"continue\?|"
    r"proceed\?"
    r")"
)
AUTO_YES_OPTION_RE = re.compile(
    r"(?im)^\s*(?:[❯›>]\s*)?1\s*[\.\:\)]\s*Yes\b"
)
AUTO_YES_YN_RE = re.compile(
    r"(?i)\[Y/n\]|\(Y/n\)|\byes\s*/\s*no\b|\b\[yes\]\s*/\s*\[no\]"
)


def auto_yes_state_path() -> Path:
    """Path for persisted auto-yes toggle + watcher pid."""
    xdg = os.environ.get("XDG_CONFIG_HOME", "").strip()
    base = Path(xdg) if xdg else (Path.home() / ".config")
    return base / "herdr" / AUTO_YES_STATE_FILENAME


def load_auto_yes_state() -> dict[str, Any]:
    path = auto_yes_state_path()
    if not path.is_file():
        return {"enabled": False, "pid": None, "log": None}
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {"enabled": False, "pid": None, "log": None}
    if not isinstance(raw, dict):
        return {"enabled": False, "pid": None, "log": None}
    return {
        "enabled": bool(raw.get("enabled")),
        "pid": raw.get("pid") if isinstance(raw.get("pid"), int) else None,
        "log": raw.get("log") if isinstance(raw.get("log"), str) else None,
    }


def save_auto_yes_state(state: dict[str, Any]) -> Path:
    path = auto_yes_state_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "enabled": bool(state.get("enabled")),
        "pid": state.get("pid") if isinstance(state.get("pid"), int) else None,
        "log": state.get("log") if isinstance(state.get("log"), str) else None,
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return path


def is_auto_yes_enabled() -> bool:
    """True when the auto-yes toggle is on (watcher may still be starting)."""
    return bool(load_auto_yes_state().get("enabled"))


def _pid_is_running(pid: int | None) -> bool:
    if not isinstance(pid, int) or pid <= 0:
        return False
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def looks_like_yes_proceed_prompt(text: str) -> bool:
    """Detect Yes/No proceed confirmations that should be auto-accepted."""
    body = text or ""
    if AUTO_YES_OPTION_RE.search(body) and (
        AUTO_YES_HINT_RE.search(body) or "Yes" in body
    ):
        return True
    if AUTO_YES_HINT_RE.search(body) and AUTO_YES_YN_RE.search(body):
        return True
    if AUTO_YES_HINT_RE.search(body) and re.search(
        r"(?im)^\s*(?:[❯›>]\s*)?1\s*[\.\:\)]\s*\S+", body
    ):
        # Numbered menu starting at 1 after a proceed hint (Yes often first).
        return True
    return False


def auto_yes_keys_for_prompt(text: str) -> list[str]:
    """Keys to send for a detected yes/proceed prompt (default: 1 + enter)."""
    body = text or ""
    if AUTO_YES_YN_RE.search(body) and not AUTO_YES_OPTION_RE.search(body):
        return ["y", "enter"]
    return ["1", "enter"]


def try_auto_yes_for_target(
    herdr: str,
    target: str,
    *,
    env: dict[str, str | None] | None = None,
    force: bool = False,
) -> bool:
    """If the target shows a Yes/proceed prompt, send Yes. Return True if sent."""
    if not force and not is_auto_yes_enabled():
        return False
    try:
        text = agent_read_text(
            herdr,
            target,
            source="detection",
            lines=40,
            max_chars=4_000,
            env=env,
        )
    except RuntimeError:
        return False
    if not looks_like_yes_proceed_prompt(text):
        return False
    keys = auto_yes_keys_for_prompt(text)
    try:
        prepare_agent(herdr, target, env=env)
        agent_send_keys(herdr, target, *keys, env=env)
    except RuntimeError:
        return False
    return True


def list_agent_targets(
    herdr: str,
    *,
    env: dict[str, str | None] | None = None,
) -> list[str]:
    """Return automation targets (name or pane_id) for live agents."""
    payload = herdr_json(herdr, ["agent", "list"], env=env)
    agents = (
        payload.get("result", {}).get("agents")
        or payload.get("agents")
        or []
    )
    out: list[str] = []
    for agent in agents:
        if not isinstance(agent, dict):
            continue
        target = automation_target_for_agent(agent)
        if target:
            out.append(target)
    return out


def run_auto_yes_watch_loop(
    *,
    herdr: str,
    poll_seconds: float = AUTO_YES_POLL_SECONDS,
    env: dict[str, str | None] | None = None,
) -> int:
    """Foreground watcher loop; exits when state.enabled becomes false."""
    last_sent: dict[str, float] = {}
    print(f"auto-yes watcher started (herdr={herdr})", flush=True)
    while True:
        state = load_auto_yes_state()
        if not state.get("enabled"):
            print("auto-yes watcher: disabled; exiting", flush=True)
            return 0
        try:
            payload = herdr_json(herdr, ["agent", "list"], env=env)
        except RuntimeError as err:
            print(f"auto-yes watcher: agent list failed: {err}", flush=True)
            time.sleep(poll_seconds)
            continue
        agents = (
            payload.get("result", {}).get("agents")
            or payload.get("agents")
            or []
        )
        now = time.monotonic()
        for agent in agents:
            if not isinstance(agent, dict):
                continue
            target = automation_target_for_agent(agent)
            if not target:
                continue
            status = agent.get("agent_status")
            # Prefer blocked panes; also scan working for sticky confirm UIs.
            if status not in {"blocked", "working", "idle", "unknown"}:
                continue
            last = last_sent.get(target, 0.0)
            if now - last < AUTO_YES_COOLDOWN_SECONDS:
                continue
            if try_auto_yes_for_target(herdr, target, env=env, force=True):
                last_sent[target] = now
                print(
                    f"auto-yes: sent Yes to {target} (status={status})",
                    flush=True,
                )
        time.sleep(poll_seconds)


def stop_auto_yes_watcher() -> None:
    """Clear enabled flag and terminate a recorded watcher pid if running."""
    state = load_auto_yes_state()
    pid = state.get("pid")
    state["enabled"] = False
    state["pid"] = None
    save_auto_yes_state(state)
    if isinstance(pid, int) and _pid_is_running(pid):
        try:
            os.kill(pid, 15)
        except OSError:
            pass


def start_auto_yes_watcher(*, herdr: str) -> dict[str, Any]:
    """Enable toggle and spawn ``auto-yes-watch`` in the background."""
    stop_auto_yes_watcher()  # ensure single watcher
    state_path = auto_yes_state_path()
    log_path = state_path.with_suffix(".log")
    script = str(Path(__file__).resolve())
    cmd = [sys.executable, script, "auto-yes-watch", "--herdr", herdr]
    log_f = open(log_path, "a", encoding="utf-8")  # noqa: SIM115
    try:
        proc = subprocess.Popen(
            cmd,
            stdin=subprocess.DEVNULL,
            stdout=log_f,
            stderr=subprocess.STDOUT,
            start_new_session=True,
            close_fds=True,
            env=os.environ.copy(),
        )
    finally:
        log_f.close()
    state = {"enabled": True, "pid": proc.pid, "log": str(log_path)}
    save_auto_yes_state(state)
    return state


def run_auto_yes_toggle(*, herdr: str) -> int:
    """Toggle auto-yes; print JSON status."""
    state = load_auto_yes_state()
    enabled = bool(state.get("enabled")) and _pid_is_running(state.get("pid"))
    if enabled:
        stop_auto_yes_watcher()
        print(
            json.dumps(
                {
                    "ok": True,
                    "enabled": False,
                    "message": "auto-yes disabled",
                    "state": str(auto_yes_state_path()),
                },
                ensure_ascii=False,
            )
        )
        return 0
    started = start_auto_yes_watcher(herdr=herdr)
    print(
        json.dumps(
            {
                "ok": True,
                "enabled": True,
                "pid": started.get("pid"),
                "log": started.get("log"),
                "message": (
                    "auto-yes enabled — Yes/proceed prompts on agent panes "
                    "will be accepted automatically"
                ),
                "state": str(auto_yes_state_path()),
            },
            ensure_ascii=False,
        )
    )
    return 0


def extract_auto_yes_argv(argv: list[str]) -> str | None:
    """Return mode ``toggle`` / ``watch`` / ``status`` when argv is auto-yes."""
    if not argv:
        return None
    first = argv[0]
    if first in {"/auto-yes", "auto-yes"}:
        if len(argv) >= 2 and argv[1] in {"status", "--status"}:
            return "status"
        if len(argv) >= 2 and argv[1] in {"watch", "auto-yes-watch"}:
            return "watch"
        return "toggle"
    if first == "auto-yes-watch":
        return "watch"
    if first.startswith("/auto-yes"):
        rem = first[len("/auto-yes") :].lstrip(" :=")
        if rem in {"status", "--status"}:
            return "status"
        return "toggle"
    return None



def main(argv: list[str] | None = None) -> int:
    # When argv is provided (tests), temporarily replace sys.argv for --daemon.
    restore_argv = False
    raw_argv = list(argv) if argv is not None else sys.argv[1:]
    herdr = os.environ.get("HERDR_BIN_PATH") or "herdr"
    if "--herdr" in raw_argv:
        idx = raw_argv.index("--herdr")
        if idx + 1 < len(raw_argv):
            herdr = raw_argv[idx + 1]

    auto_yes_mode = extract_auto_yes_argv(raw_argv)
    if auto_yes_mode == "toggle":
        return run_auto_yes_toggle(herdr=herdr)
    if auto_yes_mode == "status":
        state = load_auto_yes_state()
        running = bool(state.get("enabled")) and _pid_is_running(state.get("pid"))
        print(
            json.dumps(
                {
                    "ok": True,
                    "enabled": running,
                    "pid": state.get("pid") if running else None,
                    "log": state.get("log"),
                    "state": str(auto_yes_state_path()),
                },
                ensure_ascii=False,
            )
        )
        return 0
    if auto_yes_mode == "watch":
        # Keep enabled sticky while this process is the watcher.
        state = load_auto_yes_state()
        state["enabled"] = True
        state["pid"] = os.getpid()
        save_auto_yes_state(state)
        try:
            return run_auto_yes_watch_loop(herdr=herdr)
        finally:
            cur = load_auto_yes_state()
            if cur.get("pid") == os.getpid():
                cur["enabled"] = False
                cur["pid"] = None
                save_auto_yes_state(cur)

    turn_run = extract_turn_run_argv(raw_argv)
    if turn_run is not None:
        spec_raw, dry_run, notes_dir = turn_run
        return run_turn_run(
            herdr=herdr,
            spec_raw=spec_raw,
            dry_run=dry_run,
            notes_dir=notes_dir,
        )

    turn_init = extract_turn_init_argv(raw_argv)
    if turn_init is not None:
        names_raw, dry_run = turn_init
        return run_turn_init(herdr=herdr, names_raw=names_raw, dry_run=dry_run)

    if argv is not None:
        saved = sys.argv
        sys.argv = [sys.argv[0], *argv]
        restore_argv = True
    try:
        args = build_parser().parse_args(argv)
        try:
            return run_turns(args)
        except (RuntimeError, TimeoutError) as err:
            print(f"error: {err}", file=sys.stderr)
            return 1
    finally:
        if restore_argv:
            sys.argv = saved


if __name__ == "__main__":
    raise SystemExit(main())
