def run_turns(args: argparse.Namespace) -> int:
    try:
        workdir, notes_dir, constraints, start_turn, end_turn = prepare_run_context(
            args
        )
    except RuntimeError as err:
        print(str(err), file=sys.stderr)
        return 2

    # Fresh runs create notes; resume never wipes existing TURN* artifacts.
    ensure_notes_dir(notes_dir)

    if args.daemon and not args.dry_run:
        # Rebuild argv from sys.argv[1:] so flags stay faithful.
        return daemonize(sys.argv[1:], notes_dir=notes_dir)

    owner_reply_inject: str | None = None
    resolved_test_command = getattr(args, "test_command", None)
    resolved_acceptance = getattr(args, "acceptance", None)
    resolved_notify_webhook = getattr(args, "notify_webhook", None)
    resolved_planner_args, resolved_coder_args, resolved_reviewer_args = (
        resolve_role_agent_args(args)
    )
    task_meta_kwargs = dict(
        acceptance=resolved_acceptance,
        goal_file=getattr(args, "goal_file", None),
        acceptance_file=getattr(args, "acceptance_file", None),
        task_pack=getattr(args, "task_pack", None),
        planner_args=resolved_planner_args,
        coder_args=resolved_coder_args,
        reviewer_args=resolved_reviewer_args,
        notify_webhook=resolved_notify_webhook,
    )
    use_default_constraints = bool(
        getattr(args, "use_default_constraints", False)
    )
    if not args.resume:
        write_run_meta(
            notes_dir,
            goal=args.goal,
            workdir=workdir,
            max_turns=args.turns,
            constraints=constraints,
            use_default_constraints=use_default_constraints,
            test_command=resolved_test_command,
            **task_meta_kwargs,
        )
    else:
        # Refresh metadata with resolved goal/workdir; keep prior max_turns if present.
        meta = load_run_meta(notes_dir)
        prior_max = meta.get("max_turns")
        write_run_meta(
            notes_dir,
            goal=args.goal,
            workdir=workdir,
            max_turns=int(prior_max) if isinstance(prior_max, int) else args.turns,
            constraints=constraints,
            use_default_constraints=use_default_constraints,
            test_command=resolved_test_command,
            **task_meta_kwargs,
        )
        archived = archive_needs_owner(notes_dir)
        if archived is not None:
            print(f"resume: archived {archived.name}", flush=True)
        # Owner clarification: inject once into first turn of this resume session.
        resolved_reply = load_owner_reply_for_resume(
            notes_dir,
            cli_owner_reply=getattr(args, "owner_reply", None),
        )
        if resolved_reply is not None and should_inject_owner_reply(
            load_run_meta(notes_dir), resolved_reply
        ):
            owner_reply_inject = resolved_reply
            mark_owner_reply_consumed(notes_dir, owner_reply_inject)
            print("resume: injecting owner clarification into first turn", flush=True)

    cli_env: dict[str, str | None] | None = None
    nested: NestedPair | None = None
    try:
        if wants_nested_pair(args):
            if args.dry_run:
                planner, coder, reviewer = "director", "coder", "reviewer"
                print(
                    "dry-run: would nest a Herdr session, lay out 2x2, and start "
                    f"director/coder/reviewer (kind={args.kind})",
                    flush=True,
                )
            else:
                # Let the launcher agent finish before stealing a sibling pane.
                if os.environ.get("HERDR_PANE_ID"):
                    try:
                        launcher = resolve_from_here(args.herdr)
                        wait_until_idle(
                            args.herdr,
                            launcher,
                            grace_ms=args.daemon_idle_grace_ms,
                        )
                    except RuntimeError:
                        pass
                nested = spawn_nested_coder_reviewer(
                    args.herdr,
                    workdir=workdir,
                    kind=args.kind,
                    planner_args=resolved_planner_args,
                    coder_args=resolved_coder_args,
                    reviewer_args=resolved_reviewer_args,
                    notes_dir=notes_dir,
                )
                planner = args.planner or nested.planner
                coder = nested.coder
                reviewer = nested.reviewer
                cli_env = session_cli_env(nested.session)
                print(
                    f"nested session={nested.session} outer_pane={nested.outer_pane_id} "
                    f"director={nested.director} coder={nested.coder} "
                    f"reviewer={nested.reviewer} spare={nested.spare_pane_id} "
                    f"work_root={nested.work_root}",
                    flush=True,
                )
        else:
            planner, coder, reviewer = resolve_roles(args)
    except RuntimeError as err:
        print(str(err), file=sys.stderr)
        return 2

    session_turns = end_turn - start_turn + 1
    print(
        f"roles: planner={planner} coder={coder} reviewer={reviewer} "
        f"turns={session_turns} (absolute {start_turn}–{end_turn}) "
        f"notes={notes_dir}",
        flush=True,
    )
    if args.resume:
        print(
            f"resume: starting at turn {start_turn} "
            f"(--turns={args.turns} → end {end_turn})",
            flush=True,
        )

    if args.from_here and args.self and not args.dry_run:
        wait_until_idle(
            args.herdr,
            coder,
            grace_ms=args.daemon_idle_grace_ms,
            env=cli_env,
        )

    records: list[TurnRecord] = []
    stop_reason: str | None = None
    if args.resume:
        stop_reason = None  # filled only on early stop this session
    # COMPLETE.md only on goal-met success (DONE, or STOP+goal-met language).
    # Mutually exclusive with NEEDS_OWNER (ESCALATE / stall). See should_write_complete.
    complete_pending = False
    complete_turn: int | None = None
    complete_verdict: str | None = None
    # Webhook escalate event: true ESCALATE only (not stall → event=stop).
    escalate_notify = False
    prev_review_path: Path | None = None
    prev_result_path: Path | None = None
    if start_turn > 1:
        prev_review_path = notes_dir / f"TURN{start_turn - 1}_REVIEW.md"
        prev_result_path = notes_dir / f"TURN{start_turn - 1}_RESULT.md"
        if is_turn_artifact_pending(prev_review_path):
            prev_review_path = None
        if is_turn_artifact_pending(prev_result_path):
            prev_result_path = None
    exit_code = 0

    try:
        # --turns = max turns this invocation from start_turn (absolute end_turn).
        for turn in range(start_turn, end_turn + 1):
            plan_path = notes_dir / f"TURN{turn}_PLAN.md"
            result_path = notes_dir / f"TURN{turn}_RESULT.md"
            review_path = notes_dir / f"TURN{turn}_REVIEW.md"
            instruct_text = instruct_prompt(
                turn=turn,
                turns=end_turn,
                goal=args.goal,
                workdir=workdir,
                notes_dir=notes_dir,
                constraints=constraints,
                prev_review_path=prev_review_path,
                prev_result_path=prev_result_path,
                acceptance=resolved_acceptance,
            )
            fix_text = fix_prompt(
                turn=turn,
                turns=end_turn,
                goal=args.goal,
                workdir=workdir,
                notes_dir=notes_dir,
                constraints=constraints,
            )
            # Inject owner reply only on the first turn of this resume invocation.
            if owner_reply_inject is not None and turn == start_turn:
                prefix = format_owner_reply_prefix(owner_reply_inject)
                instruct_text = prefix + instruct_text
                fix_text = prefix + fix_text
            rec = TurnRecord(
                number=turn,
                instruct_prompt=instruct_text,
                fix_prompt=fix_text,
                review_prompt=review_prompt(
                    turn=turn,
                    turns=end_turn,
                    goal=args.goal,
                    workdir=workdir,
                    notes_dir=notes_dir,
                    acceptance=resolved_acceptance,
                ),
                apply_prompt=None,
                plan_path=plan_path,
                result_path=result_path,
                review_path=review_path,
            )
            write_skeleton(plan_path, f"Turn {turn} plan")
            write_skeleton(result_path, f"Turn {turn} result")
            write_skeleton(review_path, f"Turn {turn} review")

            print(f"======== TURN {turn}/{end_turn}: instruct ========", flush=True)
            if args.dry_run:
                print(rec.instruct_prompt)
                rec.notes.append("dry-run: skipped herdr calls")
                # Keep a pre-seeded plan (stall fixtures); otherwise write a
                # per-turn TASK so multi-turn dry-runs do not false-stall.
                if is_turn_artifact_pending(plan_path):
                    plan_path.write_text(
                        f"# Turn {turn} plan\n\n"
                        f"STATUS: CONTINUE\n"
                        f"TASK: dry-run placeholder turn {turn}\n"
                        f"DONE_WHEN: ok\n"
                        f"OUT_OF_SCOPE: none\n",
                        encoding="utf-8",
                    )
            else:
                prompt_and_wait(
                    args.herdr,
                    planner,
                    rec.instruct_prompt,
                    timeout_ms=args.timeout_ms,
                    env=cli_env,
                )

            plan_text = read_text(plan_path)
            if parse_plan_escalate(plan_text):
                rec.notes.append("planner STATUS: ESCALATE — ending before fix")
                records.append(rec)
                stop_reason = f"planner escalated at turn {turn}"
                escalate_notify = True
                write_needs_owner(
                    notes_dir,
                    goal=args.goal,
                    turn=turn,
                    why=escalate_why_excerpt(plan_text, *rec.notes),
                )
                break
            if parse_plan_stop(plan_text):
                rec.notes.append("planner STATUS: DONE/STOP — ending before fix")
                records.append(rec)
                stop_reason = f"planner stopped at turn {turn}"
                plan_kind = parse_plan_stop_kind(plan_text)
                if should_write_complete(
                    plan_status=plan_kind,
                    evidence_texts=(plan_text,),
                ):
                    complete_pending = True
                    complete_turn = turn
                    complete_verdict = f"planner {plan_kind}"
                break

            # Stall detection: continuing plan whose TASK matches the previous
            # turn's TASK (normalized) → ESCALATE for owner clarification; skip FIX.
            # Stall → NEEDS_OWNER only; never COMPLETE.md.
            if turn > 1:
                prev_plan_text = read_text(notes_dir / f"TURN{turn - 1}_PLAN.md")
                if plan_tasks_stall(plan_text, prev_plan_text):
                    task_disp = (
                        extract_labeled_field(plan_text, "TASK") or ""
                    ).strip()
                    rec.notes.append("stall: repeated TASK")
                    records.append(rec)
                    stop_reason = f"repeated TASK at turn {turn}"
                    write_needs_owner(
                        notes_dir,
                        goal=args.goal,
                        turn=turn,
                        why=(
                            f"Director replanned the same work as the previous "
                            f"turn (repeated TASK: {task_disp}). "
                            f"Owner should clarify direction or change the goal."
                        ),
                    )
                    break

            print(f"======== TURN {turn}/{end_turn}: fix ========", flush=True)
            if args.dry_run:
                print(rec.fix_prompt)
            else:
                prompt_and_wait(
                    args.herdr,
                    coder,
                    rec.fix_prompt,
                    timeout_ms=args.timeout_ms,
                    env=cli_env,
                )

            # Soft-gate: after FIX, if VERIFIED is skeleton/vague, re-prompt the
            # coder once (same turn). If still weak, prepend a note to REVIEW so
            # a soft APPROVE is less likely. At most one automatic re-ask per turn.
            weak_review_note = False
            if result_has_weak_verified(read_text(result_path)):
                reask = weak_verified_reprompt(
                    turn=turn,
                    turns=end_turn,
                    notes_dir=notes_dir,
                )
                rec.notes.append("weak-verified: re-asked once")
                print(
                    f"======== TURN {turn}/{end_turn}: "
                    f"fix (weak VERIFIED re-ask) ========",
                    flush=True,
                )
                if args.dry_run:
                    print(reask)
                else:
                    prompt_and_wait(
                        args.herdr,
                        coder,
                        reask,
                        timeout_ms=args.timeout_ms,
                        env=cli_env,
                    )
                if result_has_weak_verified(read_text(result_path)):
                    weak_review_note = True
                    rec.notes.append("weak-verified: still weak after re-ask")

            # After FIX (+ optional weak VERIFIED re-ask): collect review state
            # pack, persist TURN{n}_STATE.txt, inject into REVIEW (replaces the
            # standalone diff-summary prepend to avoid duplicate git stats).
            state_pack = collect_turn_review_pack(
                workdir,
                test_command=resolved_test_command,
            )
            state_path = write_turn_state_pack(notes_dir, turn, state_pack)
            rec.review_prompt = review_prompt(
                turn=turn,
                turns=end_turn,
                goal=args.goal,
                workdir=workdir,
                notes_dir=notes_dir,
                state_pack=state_pack,
                state_path=state_path,
                acceptance=resolved_acceptance,
            )
            if weak_review_note:
                rec.review_prompt = (
                    f"{WEAK_VERIFIED_REVIEW_NOTE}\n\n{rec.review_prompt}"
                )

            print(f"======== TURN {turn}/{end_turn}: review ========", flush=True)
            if args.dry_run:
                print(rec.review_prompt)
                # Preserve pre-seeded non-skeleton REVIEW (fixtures / DONE tests).
                if is_turn_artifact_pending(review_path):
                    review_path.write_text(
                        f"# Turn {turn} review\n\n"
                        f"VERDICT: APPROVE\n\nDry-run placeholder.\n",
                        encoding="utf-8",
                    )
            else:
                prompt_and_wait(
                    args.herdr,
                    reviewer,
                    rec.review_prompt,
                    timeout_ms=args.timeout_ms,
                    env=cli_env,
                )

            review_text = read_text(review_path)
            verdict, verdict_notes = resolve_review_verdict(review_text)
            rec.verdict = verdict
            rec.notes.extend(verdict_notes)

            if verdict == "REVISE":
                rec.apply_prompt = apply_prompt(
                    turn=turn,
                    turns=end_turn,
                    notes_dir=notes_dir,
                )
                print(f"======== TURN {turn}/{end_turn}: apply ========", flush=True)
                if args.dry_run:
                    print(rec.apply_prompt)
                else:
                    prompt_and_wait(
                        args.herdr,
                        coder,
                        rec.apply_prompt,
                        timeout_ms=args.timeout_ms,
                        env=cli_env,
                    )
            elif verdict in {"DONE", "STOP"}:
                rec.notes.append(f"review VERDICT: {verdict} — stopping loop")
                records.append(rec)
                stop_reason = f"reviewer verdict {verdict} at turn {turn}"
                if should_write_complete(
                    final_verdict=verdict,
                    evidence_texts=(review_text, plan_text),
                ):
                    complete_pending = True
                    complete_turn = turn
                    complete_verdict = verdict
                break
            elif verdict == "ESCALATE":
                # ESCALATE → NEEDS_OWNER only; never COMPLETE.md.
                rec.notes.append("review VERDICT: ESCALATE — stopping loop")
                records.append(rec)
                stop_reason = f"reviewer verdict ESCALATE at turn {turn}"
                escalate_notify = True
                write_needs_owner(
                    notes_dir,
                    goal=args.goal,
                    turn=turn,
                    why=escalate_why_excerpt(
                        review_text,
                        read_text(plan_path),
                        *rec.notes,
                    ),
                )
                break

            records.append(rec)
            prev_review_path = review_path
            prev_result_path = result_path

        summary_stop = stop_reason
        if args.resume and summary_stop is not None:
            summary_stop = f"resumed from turn {start_turn}; {summary_stop}"
        summary = render_summary(
            records,
            goal=args.goal,
            notes_dir=notes_dir,
            max_turns=session_turns,
            stop_reason=summary_stop,
        )
        report_path = write_and_display_summary(
            summary,
            workdir=workdir,
            notes_dir=notes_dir,
        )
        if complete_pending and complete_turn is not None and complete_verdict:
            write_complete_md(
                notes_dir,
                goal=args.goal,
                turn=complete_turn,
                stop_reason=summary_stop,
                final_verdict=complete_verdict,
                summary_path=notes_dir / "SUMMARY.md",
                report_path=report_path,
            )
        # Terminal webhook (optional): after summary / COMPLETE are settled.
        if resolved_notify_webhook:
            last = records[-1] if records else None
            if complete_pending:
                hook_event = "complete"
                hook_turn = complete_turn
                hook_verdict = complete_verdict
            elif escalate_notify:
                hook_event = "escalate"
                hook_turn = last.number if last is not None else None
                hook_verdict = (
                    last.verdict
                    if last is not None and last.verdict
                    else "ESCALATE"
                )
            else:
                hook_event = "stop"
                hook_turn = last.number if last is not None else None
                hook_verdict = last.verdict if last is not None else None
            notify_turns_webhook(
                resolved_notify_webhook,
                event=hook_event,
                goal=args.goal,
                turn=hook_turn,
                verdict=hook_verdict,
                stop_reason=summary_stop,
                notes_dir=notes_dir,
                workdir=workdir,
            )
        if nested is not None and not args.dry_run:
            try:
                deliver_summary_to_caller(
                    args.herdr,
                    summary,
                    report_path=report_path,
                    notes_dir=notes_dir,
                    timeout_ms=args.timeout_ms,
                )
            except (RuntimeError, TimeoutError) as err:
                print(f"warning: summary delivery failed: {err}", flush=True)
            if args.keep_nested:
                print(
                    f"nested session left running: {nested.session} "
                    f"(outer pane {nested.outer_pane_id})",
                    flush=True,
                )
    except (RuntimeError, TimeoutError) as err:
        print(f"error: {err}", file=sys.stderr)
        exit_code = 1
    finally:
        if (
            nested is not None
            and not args.dry_run
            and not args.keep_nested
        ):
            cleanup_nested_pair(args.herdr, nested)

    return exit_code


def main(argv: list[str] | None = None) -> int:
    # When argv is provided (tests), temporarily replace sys.argv for --daemon.
    restore_argv = False
    if argv is not None:
        saved = sys.argv
        sys.argv = [sys.argv[0], *argv]
        restore_argv = True
    try:
        args = build_parser().parse_args(argv)
        try:
            return run_turns(args)
        except (RuntimeError, TimeoutError) as err:
            print(f"error: {err}", file=sys.stderr)
            return 1
    finally:
        if restore_argv:
            sys.argv = saved


if __name__ == "__main__":
    raise SystemExit(main())
