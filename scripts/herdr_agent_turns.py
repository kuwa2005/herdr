def owner_reply_digest(text: str) -> str:
    """SHA-256 hex digest of stripped owner-reply text (stable consumption key)."""
    return hashlib.sha256(text.strip().encode("utf-8")).hexdigest()


def content_digest(text: str) -> str:
    """SHA-256 of stripped UTF-8 text (same normalization as owner_reply_digest)."""
    return owner_reply_digest(text)


def read_trimmed_file(path: Path) -> str:
    """Read a UTF-8 file and return stripped contents.

    Raises ``RuntimeError`` when the file is missing, unreadable, or empty
    after strip (exit path: prepare_run_context → exit 2).
    """
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise RuntimeError(f"cannot read {path}: {exc}") from exc
    stripped = text.strip()
    if not stripped:
        raise RuntimeError(f"file is empty: {path}")
    return stripped


def _extract_yaml_top_level(text: str, key: str) -> str | None:
    """Minimal top-level YAML ``key:`` extractor (no full YAML dependency).

    Supports plain scalars, single/double quotes, and ``|`` / ``>`` blocks.
    Only matches keys at column 0 (not nested mappings).
    """
    lines = text.splitlines()
    key_re = re.compile(rf"^{re.escape(key)}\s*:\s*(.*)$", re.IGNORECASE)
    i = 0
    while i < len(lines):
        match = key_re.match(lines[i])
        if match is None:
            i += 1
            continue
        rest = match.group(1).rstrip()
        rest_stripped = rest.strip()
        if rest_stripped in {"|", ">", "|-", "|+", ">-", ">+"} or rest_stripped.startswith(
            ("|", ">")
        ):
            block: list[str] = []
            i += 1
            while i < len(lines):
                line = lines[i]
                if line.strip() == "":
                    block.append("")
                    i += 1
                    continue
                if line[:1] in {" ", "\t"}:
                    block.append(line)
                    i += 1
                    continue
                break
            if not block:
                return None
            # Dedent by shortest leading indent among non-empty lines.
            indents = [
                len(ln) - len(ln.lstrip(" \t"))
                for ln in block
                if ln.strip()
            ]
            pad = min(indents) if indents else 0
            dedented = [
                ln[pad:] if len(ln) >= pad else ln for ln in block
            ]
            value = "\n".join(dedented).strip()
            return value or None
        if len(rest_stripped) >= 2 and (
            (rest_stripped[0] == rest_stripped[-1] == '"')
            or (rest_stripped[0] == rest_stripped[-1] == "'")
        ):
            return rest_stripped[1:-1].strip() or None
        return rest_stripped or None
    return None


def _extract_md_section(text: str, titles: tuple[str, ...]) -> str | None:
    """Return the body of the first matching AT1–H6 section title."""
    for title in titles:
        pattern = re.compile(
            rf"(?ims)^\s*#{{1,6}}\s*{re.escape(title)}\s*\n+(.*?)(?=^\s*#{{1,6}}\s|\Z)"
        )
        match = pattern.search(text)
        if match is None:
            continue
        body = match.group(1).strip()
        if body:
            return body
    return None


def parse_task_pack_text(text: str) -> tuple[str, str | None]:
    """Parse goal (+ optional acceptance) from task-pack YAML or Markdown text.

    YAML (minimal): top-level ``goal:`` / ``acceptance:``.
    Markdown: ``# Goal`` / ``## Goal`` and ``## Acceptance`` /
    ``## Acceptance criteria``. YAML keys win when ``goal:`` is present.
    """
    goal = _extract_yaml_top_level(text, "goal")
    acceptance = _extract_yaml_top_level(text, "acceptance")
    if goal and goal.strip():
        acc = acceptance.strip() if acceptance and acceptance.strip() else None
        return goal.strip(), acc
    goal_md = _extract_md_section(text, ("Goal",))
    acceptance_md = _extract_md_section(
        text, ("Acceptance criteria", "Acceptance")
    )
    if goal_md and goal_md.strip():
        acc = (
            acceptance_md.strip()
            if acceptance_md and acceptance_md.strip()
            else None
        )
        return goal_md.strip(), acc
    return "", None


def load_task_pack(path: Path) -> tuple[str, str | None]:
    """Load ``(goal, acceptance)`` from a YAML or Markdown task pack file.

    Raises ``RuntimeError`` when unreadable or goal is empty.
    """
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise RuntimeError(f"cannot read task pack {path}: {exc}") from exc
    goal, acceptance = parse_task_pack_text(raw)
    if not goal:
        raise RuntimeError(f"task pack has empty or missing goal: {path}")
    return goal, acceptance


def _optional_path(value: Any) -> Path | None:
    if value is None:
        return None
    if isinstance(value, Path):
        return value.expanduser()
    if isinstance(value, str) and value.strip():
        return Path(value.strip()).expanduser()
    return None


def resolve_goal_and_acceptance(
    args: argparse.Namespace,
    *,
    meta: dict[str, Any] | None = None,
    notes_dir: Path | None = None,
) -> tuple[str, str | None]:
    """Resolve overall goal and optional acceptance for this invocation.

    **Goal precedence** (first non-empty wins):
    1. CLI ``--goal``
    2. ``--goal-file`` contents
    3. ``--task-pack`` goal
    4. On ``--resume`` only: re-read meta ``goal_file`` / ``task_pack`` if
       present on disk; else ``run.json`` ``goal``; else ``NEEDS_OWNER`` Goal

    **Acceptance precedence**:
    1. ``--acceptance-file`` contents
    2. ``--task-pack`` acceptance (when pack is used this invocation)
    3. On ``--resume``: re-read meta ``acceptance_file`` / ``task_pack``;
       else ``run.json`` ``acceptance`` string

    Resume file-missing policy: if a meta path is set but the file is gone,
    fall back to stored ``goal`` / ``acceptance`` text in ``run.json`` (do not
    hard-fail solely because the source file moved). Still error when no goal
    string can be resolved at all.

    Side effects: sets ``args.goal``, ``args.acceptance``, and resolved path
    attributes ``goal_file`` / ``acceptance_file`` / ``task_pack`` (Path|None).
    """
    meta = meta or {}
    resume = bool(getattr(args, "resume", False))

    cli_goal = (getattr(args, "goal", None) or "").strip() or None
    goal_file = _optional_path(getattr(args, "goal_file", None))
    acceptance_file = _optional_path(getattr(args, "acceptance_file", None))
    task_pack = _optional_path(getattr(args, "task_pack", None))

    # On resume, restore paths from meta when CLI omitted them.
    if resume:
        if goal_file is None and isinstance(meta.get("goal_file"), str):
            goal_file = _optional_path(meta.get("goal_file"))
        if acceptance_file is None and isinstance(meta.get("acceptance_file"), str):
            acceptance_file = _optional_path(meta.get("acceptance_file"))
        if task_pack is None and isinstance(meta.get("task_pack"), str):
            task_pack = _optional_path(meta.get("task_pack"))

    pack_goal: str | None = None
    pack_acceptance: str | None = None
    if task_pack is not None:
        if task_pack.is_file():
            pack_goal, pack_acceptance = load_task_pack(task_pack)
        elif not resume:
            raise RuntimeError(f"--task-pack does not exist: {task_pack}")
        # resume + missing file: fall through to meta strings

    file_goal: str | None = None
    if goal_file is not None:
        if goal_file.is_file():
            file_goal = read_trimmed_file(goal_file)
        elif not resume:
            raise RuntimeError(f"--goal-file does not exist: {goal_file}")

    file_acceptance: str | None = None
    if acceptance_file is not None:
        if acceptance_file.is_file():
            file_acceptance = read_trimmed_file(acceptance_file)
        elif not resume:
            raise RuntimeError(
                f"--acceptance-file does not exist: {acceptance_file}"
            )

    # Goal: CLI > goal-file > task-pack > (resume meta / NEEDS_OWNER)
    goal = cli_goal or file_goal or pack_goal
    if goal is None and resume:
        meta_goal = meta.get("goal")
        if isinstance(meta_goal, str) and meta_goal.strip():
            goal = meta_goal.strip()
        if goal is None and notes_dir is not None:
            goal = parse_goal_from_needs_owner(notes_dir)

    # Acceptance: acceptance-file > task-pack > (resume meta text)
    acceptance = file_acceptance or pack_acceptance
    if acceptance is None and resume:
        meta_acc = meta.get("acceptance")
        if isinstance(meta_acc, str) and meta_acc.strip():
            acceptance = meta_acc.strip()

    if not goal:
        if resume:
            raise RuntimeError(
                "--resume: no goal; pass --goal / --goal-file / --task-pack "
                "or ensure run.json / NEEDS_OWNER.md contains one"
            )
        raise RuntimeError(
            "--goal is required unless --goal-file / --task-pack "
            "(or --resume with run.json / NEEDS_OWNER.md) provides one"
        )

    args.goal = goal
    args.acceptance = acceptance
    args.goal_file = goal_file.resolve() if goal_file is not None else None
    args.acceptance_file = (
        acceptance_file.resolve() if acceptance_file is not None else None
    )
    args.task_pack = task_pack.resolve() if task_pack is not None else None
    return goal, acceptance


