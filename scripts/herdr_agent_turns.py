#!/usr/bin/env python3
"""Self-evolving instruct → fix → review loop via Herdr agent CLI.

Official multi-agent improvement workflow for this Herdr fork:

1. INSTRUCT — director plans the next focused task (``TURN{n}_PLAN.md``)
2. FIX — coder implements that plan (``TURN{n}_RESULT.md``)
3. REVIEW — reviewer judges and writes instructions (``TURN{n}_REVIEW.md``)
4. Optional APPLY — coder applies review when verdict is ``REVISE``
5. Next turn's INSTRUCT reads the prior review and plans further improvement

Hard cap: at most ``MAX_TURNS`` (10). Infinite or huge turn counts are rejected.
Early stop when review verdict is ``DONE`` (goal met), ``STOP``, or ``ESCALATE``
(owner judgment required; writes ``NEEDS_OWNER.md``). Successful goal-met
stops also write ``COMPLETE.md`` (see ``should_write_complete``).

Typical in-session call (from a Herdr-managed agent pane):

    herdr-turns --from-here --daemon --turns 5 --goal "Improve error handling"

``--from-here`` (default path) nests a disposable Herdr session in a sibling
pane, lays out a 2x2 grid, and starts ``director`` / ``coder`` / ``reviewer``
(fourth pane stays a plain shell). ``--daemon`` backgrounds the runner so the
launcher agent can go idle (avoids deadlock). When turns finish, the runner
delivers the full-turn summary to the launcher agent and stops the nested
session (use ``--keep-nested`` to leave it).

Use ``--self`` to keep the old single-pane self-review mode. Explicit
``--coder`` / ``--reviewer`` (without ``--from-here``) targets existing agents.

Wave 3 (AI-driven): ``--goal-file`` / ``--task-pack``, ``--test-command``,
per-role ``--*-arg``, bundled default constraints, ``--notify-webhook`` —
see ``FORK.md`` 「AI駆動・自己進化（wave 3）」.
"""

