DIFF_SUMMARY_HEADER = "Uncommitted diff summary (workdir):"
DIFF_SUMMARY_MAX_CHARS = 2000
STATE_PACK_HEADER = "Turn review state pack:"
REVIEW_PACK_MAX_CHARS = 12_000
REVIEW_PACK_DIFF_MAX_CHARS = 4_000
REVIEW_PACK_STATUS_MAX_CHARS = 2_000
REVIEW_PACK_TEST_MAX_CHARS = 4_000
REVIEW_PACK_TEST_TIMEOUT_S = 120


def _truncate_chars(text: str, max_chars: int) -> str:
    """Truncate *text* to *max_chars*, appending a visible suffix when cut."""
    if max_chars <= 0 or len(text) <= max_chars:
        return text
    suffix = "… (truncated)"
    keep = max(0, max_chars - len(suffix))
    return text[:keep] + suffix


def collect_workdir_diff_summary(
    workdir: Path,
    *,
    max_chars: int = DIFF_SUMMARY_MAX_CHARS,
    runner: Any | None = None,
) -> str | None:
    """Return a short uncommitted diff summary from *workdir*, or ``None``.

    Runs only ``git diff --stat`` and ``git diff --name-status`` (no full
    patches). Missing git, non-repo, non-zero exit, or empty output → ``None``.
    *runner* defaults to ``subprocess.run`` (injectable for tests).
    """
    run = runner if runner is not None else subprocess.run
    parts: list[str] = []
    for args in (
        ["git", "diff", "--stat"],
        ["git", "diff", "--name-status"],
    ):
        try:
            completed = run(
                args,
                cwd=str(workdir),
                capture_output=True,
                text=True,
                timeout=15,
                check=False,
            )
        except (OSError, subprocess.SubprocessError):
            return None
        if getattr(completed, "returncode", 1) != 0:
            return None
        out = (getattr(completed, "stdout", None) or "").strip()
        if out:
            parts.append(out)
    if not parts:
        return None
    text = "\n\n".join(parts)
    return _truncate_chars(text, max_chars)


def collect_turn_review_pack(
    workdir: Path,
    *,
    test_command: str | None = None,
    max_diff_chars: int = REVIEW_PACK_DIFF_MAX_CHARS,
    max_pack_chars: int = REVIEW_PACK_MAX_CHARS,
    runner: Any | None = None,
    status_runner: Any | None = None,
    test_runner: Any | None = None,
) -> str:
    """Build a bounded review artifact pack for ``TURN{n}_STATE`` / REVIEW.

    Includes ``git status --short``, ``collect_workdir_diff_summary``, a
    truncated ``git diff``, and optional ``test_command`` exit code + output.
    Git / command failures become ``(unavailable)`` sections (never raise).
    *runner* / *status_runner* / *test_runner* default to ``subprocess.run``
    (injectable for tests; same pattern as ``collect_workdir_diff_summary``).
    """
    run = runner if runner is not None else subprocess.run
    status_run = status_runner if status_runner is not None else run
    sections: list[str] = []

    status_section = "## git status --short\n"
    try:
        completed = status_run(
            ["git", "status", "--short"],
            cwd=str(workdir),
            capture_output=True,
            text=True,
            timeout=15,
            check=False,
        )
        if getattr(completed, "returncode", 1) != 0:
            status_section += "(unavailable)"
        else:
            out = (getattr(completed, "stdout", None) or "").rstrip()
            if out:
                status_section += _truncate_chars(
                    out, REVIEW_PACK_STATUS_MAX_CHARS
                )
            else:
                status_section += "(clean)"
    except (OSError, subprocess.SubprocessError):
        status_section += "(unavailable)"
    sections.append(status_section)

    summary = collect_workdir_diff_summary(workdir, runner=run)
    summary_section = "## diff summary (stat / name-status)\n"
    if summary:
        summary_section += summary
    else:
        summary_section += "(unavailable)"
    sections.append(summary_section)

    diff_section = "## git diff (truncated)\n"
    try:
        completed = run(
            ["git", "diff"],
            cwd=str(workdir),
            capture_output=True,
            text=True,
            timeout=15,
            check=False,
        )
        if getattr(completed, "returncode", 1) != 0:
            diff_section += "(unavailable)"
        else:
            out = (getattr(completed, "stdout", None) or "").rstrip()
            if out:
                diff_section += _truncate_chars(out, max_diff_chars)
            else:
                diff_section += "(empty)"
    except (OSError, subprocess.SubprocessError):
        diff_section += "(unavailable)"
    sections.append(diff_section)

    cmd = (test_command or "").strip()
    if cmd:
        test_section = f"## test_command\n$ {cmd}\n"
        t_run = test_runner if test_runner is not None else subprocess.run
        try:
            completed = t_run(
                cmd,
                cwd=str(workdir),
                shell=True,
                capture_output=True,
                text=True,
                timeout=REVIEW_PACK_TEST_TIMEOUT_S,
                check=False,
            )
            code = getattr(completed, "returncode", -1)
            stdout = getattr(completed, "stdout", None) or ""
            stderr = getattr(completed, "stderr", None) or ""
            combined = stdout
            if stderr.strip():
                combined = (
                    f"{combined}\n--- stderr ---\n{stderr}"
                    if combined
                    else stderr
                )
            combined = combined.rstrip()
            test_section += f"exit_code: {code}\n"
            if combined:
                test_section += _truncate_chars(
                    combined, REVIEW_PACK_TEST_MAX_CHARS
                )
            else:
                test_section += "(no output)"
        except subprocess.TimeoutExpired:
            test_section += "exit_code: (timeout)\n(unavailable)"
        except (OSError, subprocess.SubprocessError):
            test_section += "exit_code: (unavailable)\n(unavailable)"
        sections.append(test_section)

    return _truncate_chars("\n\n".join(sections), max_pack_chars)


