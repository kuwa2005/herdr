def review_prompt(
    *,
    turn: int,
    turns: int,
    goal: str,
    workdir: Path,
    notes_dir: Path,
    diff_summary: str | None = None,
    state_pack: str | None = None,
    state_path: Path | str | None = None,
    acceptance: str | None = None,
) -> str:
    # Reviewer rules mirrored by is_skeleton_verified() for tests:
    # vague/empty/pending VERIFIED → REVISE; unmet DONE_WHEN → prefer REVISE.
    plan_path = notes_dir / f"TURN{turn}_PLAN.md"
    result_path = notes_dir / f"TURN{turn}_RESULT.md"
    review_path = notes_dir / f"TURN{turn}_REVIEW.md"
    acceptance_block = format_acceptance_block(acceptance)
    acceptance_note = (
        "Use acceptance criteria together with DONE_WHEN when judging "
        "DONE vs REVISE against the overall goal.\n"
        if acceptance_block
        else ""
    )
    body = (
        f"Turn {turn}/{turns} REVIEW (self-review).\n"
        f"Workdir: {workdir}\n"
        f"Overall goal: {goal}\n"
        f"{acceptance_block}"
        f"{acceptance_note}"
        f"Read {plan_path} (including DONE_WHEN) and {result_path}. "
        f"Review the current uncommitted work (git diff / new files) and "
        f"compare it against DONE and FILES.\n"
        f"Write {review_path} using exactly these labeled lines "
        f"(needed later for effectiveness review):\n"
        f"VERDICT: APPROVE|REVISE|DONE|ESCALATE\n"
        f"IMPROVE: <what must change next, or none>\n"
        f"EFFECT: <did this turn move the overall goal? yes/partial/no + one reason>\n"
        f"- APPROVE: plan DONE_WHEN is met (or clearly out of scope this turn); "
        f"next instruct may still improve further\n"
        f"- REVISE: coder must apply IMPROVE this turn — prefer REVISE when "
        f"DONE_WHEN is not met, or when VERIFIED is missing/empty/_(pending)_/"
        f"not a concrete command or check (tell coder to re-run and document "
        f"verification; reject vague VERIFIED like \"looks good\")\n"
        f"- DONE: overall goal is met; stop the loop\n"
        f"- ESCALATE: human owner judgment is required; stop the loop\n"
        f"Do not edit repository source files yourself."
    )
    # Prefer the unified state pack (wave 3). Do not also inject the legacy
    # DIFF_SUMMARY_HEADER block — pack already includes stat/name-status.
    pack = (state_pack or "").strip()
    if pack:
        path_note = ""
        if state_path is not None:
            path_note = (
                f"Full review state pack file: {state_path}\n"
                f"(state pack body below; prefer this file for the full text)\n"
            )
        return f"{path_note}{STATE_PACK_HEADER}\n{pack}\n\n{body}"
    # Legacy callers/tests: single diff-summary prepend.
    summary = (diff_summary or "").strip()
    if summary:
        return f"{DIFF_SUMMARY_HEADER}\n{summary}\n\n{body}"
    return body


def is_skeleton_verified(value: str | None) -> bool:
    """True when VERIFIED is missing/empty/pending/vague.

    Mirrors review_prompt guidance. Used by the post-FIX soft-gate and tests;
    does not rewrite reviewer VERDICT text.
    """
    if value is None:
        return True
    text = " ".join(value.strip().split())
    if not text or text == "_(pending)_":
        return True
    lowered = text.lower()
    vague = (
        "looks good",
        "manual review",
        "should work",
        "seems fine",
        "lgtm",
    )
    if lowered in vague:
        return True
    if any(lowered == v or lowered.startswith(v + ".") for v in vague):
        return True
    # Exact short hand-wavy phrases only; longer text with a command is ok.
    if lowered in {"ok", "fine", "done", "passed", "pass"}:
        return True
    return False


