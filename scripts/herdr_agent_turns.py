def validate_turns(turns: int) -> str | None:
    if turns < 1:
        return "--turns must be >= 1"
    if turns > MAX_TURNS:
        return f"--turns must be <= {MAX_TURNS} (hard cap; infinite loops are forbidden)"
    return None


def automation_target_for_agent(agent: dict[str, Any]) -> str | None:
    name = agent.get("name")
    if isinstance(name, str) and name.strip():
        return name.strip()
    pane_id = agent.get("pane_id")
    if isinstance(pane_id, str) and pane_id.strip():
        return pane_id.strip()
    terminal_id = agent.get("terminal_id")
    if isinstance(terminal_id, str) and terminal_id.strip():
        return terminal_id.strip()
    return None


def resolve_agent_in_pane(herdr: str, pane_id: str) -> str:
    payload = herdr_json(herdr, ["agent", "list"])
    agents = payload.get("result", {}).get("agents") or payload.get("agents") or []
    matches: list[str] = []
    for agent in agents:
        if not isinstance(agent, dict):
            continue
        if str(agent.get("pane_id") or "") != pane_id:
            continue
        target = automation_target_for_agent(agent)
        if target:
            matches.append(target)
    if not matches:
        raise RuntimeError(
            f"--from-here: no live agent in pane {pane_id!r} "
            "(start an agent in this pane, or pass --coder explicitly)"
        )
    if len(matches) > 1:
        raise RuntimeError(
            f"--from-here: multiple agents in pane {pane_id!r}: {matches}"
        )
    return matches[0]


def resolve_from_here(herdr: str) -> str:
    pane_id = os.environ.get("HERDR_PANE_ID", "").strip()
    if not pane_id:
        raise RuntimeError(
            "--from-here requires HERDR_PANE_ID "
            "(run inside a Herdr-managed pane, or pass --coder)"
        )
    return resolve_agent_in_pane(herdr, pane_id)


def resolve_roles(args: argparse.Namespace) -> tuple[str, str, str]:
    """Return (planner, coder, reviewer) for non-spawn modes."""
    coder = args.coder
    if args.from_here and args.self:
        here = resolve_from_here(args.herdr)
        coder = coder or here
    if not coder:
        raise RuntimeError("pass --coder, or --from-here (nested team / --self)")
    planner = args.planner or coder
    reviewer = args.reviewer or coder
    return planner, coder, reviewer


def wants_nested_pair(args: argparse.Namespace) -> bool:
    """True when --from-here should nest a 2x2 director/coder/reviewer team."""
    return bool(args.from_here) and not bool(args.self)


def default_notes_dir(args: argparse.Namespace) -> Path:
    if args.notes_dir is not None:
        return args.notes_dir.expanduser().resolve()
    if args.from_here:
        return (Path.cwd() / "herdr-turns-notes").resolve()
    raise RuntimeError("--notes-dir is required unless --from-here")


def session_cli_env(session: str) -> dict[str, str | None]:
    """Env for parent-process CLI calls that must address a named session."""
    return {
        "HERDR_SESSION": session,
        "HERDR_SOCKET_PATH": None,
        "HERDR_CLIENT_SOCKET_PATH": None,
        "HERDR_WORKSPACE_ID": None,
        "HERDR_TAB_ID": None,
        "HERDR_PANE_ID": None,
    }


@dataclass
class NestedPair:
    session: str
    outer_pane_id: str
    director: str
    coder: str
    reviewer: str
    planner: str
    spare_pane_id: str
    config_path: Path
    work_root: Path


def _result_pane_id(payload: dict[str, Any]) -> str:
    pane = (payload.get("result") or {}).get("pane") or {}
    pane_id = pane.get("pane_id")
    if not isinstance(pane_id, str) or not pane_id.strip():
        raise RuntimeError(f"pane response missing pane_id: {payload!r}")
    return pane_id.strip()


def assign_nested_2x2_panes(
    root_pane: str,
    right_of_root: str,
    down_of_root: str,
    down_of_right: str,
) -> dict[str, str]:
    """Map sequential split results onto the nested 2x2 role layout.

    After ``root → split right → split root down → split right-pane down``:

        director | coder
        ---------+------
        reviewer | spare
    """
    return {
        "director": root_pane,
        "coder": right_of_root,
        "reviewer": down_of_root,
        "spare": down_of_right,
    }


def write_nested_config(work_root: Path) -> Path:
    work_root.mkdir(parents=True, exist_ok=True)
    path = work_root / "config.toml"
    path.write_text(NESTED_CONFIG_TOML, encoding="utf-8")
    return path


def wait_for_session_panes(
    herdr: str,
    session: str,
    *,
    timeout_s: float = DEFAULT_SPAWN_READY_TIMEOUT_S,
) -> list[dict[str, Any]]:
    deadline = time.monotonic() + timeout_s
    last_err: str | None = None
    while time.monotonic() < deadline:
        try:
            payload = herdr_json(
                herdr, ["pane", "list"], env=session_cli_env(session)
            )
            panes = (payload.get("result") or {}).get("panes") or []
            if isinstance(panes, list) and panes:
                return [p for p in panes if isinstance(p, dict)]
            last_err = "pane list empty"
        except RuntimeError as err:
            last_err = str(err)
        time.sleep(DEFAULT_POLL_SECONDS)
    raise RuntimeError(
        f"nested session {session!r} not ready within {timeout_s:.0f}s"
        + (f": {last_err}" if last_err else "")
    )


def nested_herdr_launch_command(
    herdr: str,
    *,
    session: str,
    config_path: Path,
) -> str:
    """One shell command line typed into the outer pane via ``pane run``.

    ``pane run`` joins argv with spaces into a single prompt line, so this must
    be passed as **one** COMMAND argument (not ``bash -lc <words...>`` — that
    makes ``-c`` receive only the first word).

    Do not put ``--session`` on the parent ``herdr pane run`` argv; the parent
    CLI would interpret it and talk to a not-yet-running socket. Use
    ``HERDR_SESSION`` in the pane shell instead.
    """
    return (
        "exec env "
        "-u HERDR_SOCKET_PATH -u HERDR_CLIENT_SOCKET_PATH "
        "-u HERDR_WORKSPACE_ID -u HERDR_TAB_ID -u HERDR_PANE_ID "
        f"HERDR_CONFIG_PATH={shlex.quote(str(config_path))} "
        f"HERDR_SESSION={shlex.quote(session)} "
        f"{shlex.quote(herdr)}"
    )


def _split_nested_pane(
    herdr: str,
    session: str,
    pane_id: str,
    *,
    direction: str,
    workdir: Path,
) -> str:
    payload = herdr_json(
        herdr,
        [
            "pane",
            "split",
            "--direction",
            direction,
            "--no-focus",
            "--cwd",
            str(workdir),
            pane_id,
        ],
        env=session_cli_env(session),
    )
    return _result_pane_id(payload)


def _rename_nested_pane(
    herdr: str,
    session: str,
    pane_id: str,
    label: str,
) -> None:
    try:
        herdr_run(
            herdr,
            ["pane", "rename", pane_id, label],
            env=session_cli_env(session),
            allow_empty=True,
        )
    except RuntimeError as err:
        print(f"warning: pane rename {pane_id} -> {label}: {err}", flush=True)


def spawn_nested_coder_reviewer(
    herdr: str,
    *,
    workdir: Path,
    kind: str,
    agent_args: list[str],
    parent_pane_id: str | None = None,
    notes_dir: Path | None = None,
) -> NestedPair:
    """Nest Herdr in a sibling pane, lay out 2x2, start director/coder/reviewer."""
    parent_pane = (
        parent_pane_id or load_launcher_pane(notes_dir) or ""
    ).strip()
    if not parent_pane:
        raise RuntimeError(
            "nested team requires HERDR_PANE_ID "
            "(run inside a Herdr-managed pane with --from-here)"
        )
    herdr_env = os.environ.get("HERDR_ENV", "").strip()
    if herdr_env != "1" and notes_dir is not None:
        try:
            herdr_env = (notes_dir / "launcher-herdr-env").read_text(
                encoding="utf-8"
            ).strip()
        except OSError:
            herdr_env = ""
    if herdr_env != "1":
        raise RuntimeError(
            "nested team requires HERDR_ENV=1 (run inside a Herdr-managed pane)"
        )

    stamp = datetime.now().strftime("%Y%m%d%H%M%S")
    session = f"turns-{stamp}"
    work_root = Path("/var/tmp") / f"herdr-turns-{stamp}"
    config_path = write_nested_config(work_root)
    notes_hint = work_root / "README.txt"
    notes_hint.write_text(
        f"Nested turns session={session}\nconfig={config_path}\n"
        "layout: director|coder / reviewer|spare\n",
        encoding="utf-8",
    )

    print(
        f"spawning nested session {session} in sibling of {parent_pane} "
        f"(kind={kind}, layout=2x2 director/coder/reviewer/spare)",
        flush=True,
    )
    split_payload = herdr_json(
        herdr,
        [
            "pane",
            "split",
            "--direction",
            "right",
            "--no-focus",
            "--cwd",
            str(workdir),
            parent_pane,
        ],
    )
    outer_pane = _result_pane_id(split_payload)

    # Launch nested TUI/server in the new outer pane via the pane's shell.
    # Pass the whole line as one COMMAND so pane run's join does not break it.
    launch_cmd = nested_herdr_launch_command(
        herdr, session=session, config_path=config_path
    )
    try:
        # pane run is Quiet — empty stdout on success.
        herdr_run(
            herdr,
            ["pane", "run", outer_pane, launch_cmd],
            allow_empty=True,
        )
    except RuntimeError:
        try:
            herdr_json(herdr, ["pane", "close", outer_pane])
        except RuntimeError:
            pass
        raise

    nested_panes = wait_for_session_panes(herdr, session)
    root_pane = str(nested_panes[0].get("pane_id") or "").strip()
    if not root_pane:
        raise RuntimeError(f"nested session {session!r}: root pane missing id")

    # 2x2: TL director, TR coder, BL reviewer, BR spare (shell only).
    coder_pane = _split_nested_pane(
        herdr, session, root_pane, direction="right", workdir=workdir
    )
    reviewer_pane = _split_nested_pane(
        herdr, session, root_pane, direction="down", workdir=workdir
    )
    spare_pane = _split_nested_pane(
        herdr, session, coder_pane, direction="down", workdir=workdir
    )
    roles = assign_nested_2x2_panes(
        root_pane, coder_pane, reviewer_pane, spare_pane
    )

    for label, pane_id in (
        ("director", roles["director"]),
        ("coder", roles["coder"]),
        ("reviewer", roles["reviewer"]),
        ("spare", roles["spare"]),
    ):
        _rename_nested_pane(herdr, session, pane_id, label)

    start_extra: list[str] = []
    if agent_args:
        start_extra = ["--", *agent_args]
    for name in ("director", "coder", "reviewer"):
        pane_id = roles[name]
        print(f"starting agent {name} on {pane_id} (kind={kind})", flush=True)
        herdr_json(
            herdr,
            [
                "agent",
                "start",
                name,
                "--kind",
                kind,
                "--pane",
                pane_id,
                *start_extra,
            ],
            env=session_cli_env(session),
        )
    print(
        f"spare pane {roles['spare']} left as shell (no agent)",
        flush=True,
    )

    return NestedPair(
        session=session,
        outer_pane_id=outer_pane,
        director="director",
        coder="coder",
        reviewer="reviewer",
        planner="director",
        spare_pane_id=roles["spare"],
        config_path=config_path,
        work_root=work_root,
    )


def cleanup_nested_session(herdr: str, session: str) -> None:
    # Address the session catalog from the parent process (no HERDR_SESSION).
    try:
        herdr_json(herdr, ["session", "stop", session])
    except RuntimeError as err:
        print(f"warning: session stop {session}: {err}", flush=True)
    try:
        herdr_json(herdr, ["session", "delete", session])
    except RuntimeError as err:
        print(f"warning: session delete {session}: {err}", flush=True)


def cleanup_nested_pair(herdr: str, nested: NestedPair) -> None:
    """Stop nested agents/session and close the outer sibling pane."""
    print(f"cleanup: stopping nested session {nested.session}", flush=True)
    cleanup_nested_session(herdr, nested.session)
    try:
        herdr_json(herdr, ["pane", "close", nested.outer_pane_id])
        print(f"cleanup: closed outer pane {nested.outer_pane_id}", flush=True)
    except RuntimeError as err:
        print(
            f"warning: pane close {nested.outer_pane_id}: {err}",
            flush=True,
        )


def launcher_summary_prompt(*, summary: str, report_path: Path, notes_dir: Path) -> str:
    """Prompt text that asks the caller agent to present the turn summary."""
    return (
        "自己改善ターンが完了しました。"
        "以下の全ターンサマリーをユーザーへ簡潔に伝えてください。"
        "追加のコード変更やコミットは不要です。\n\n"
        f"レポートファイル: `{report_path}`\n"
        f"SUMMARY: `{notes_dir / 'SUMMARY.md'}`\n\n"
        f"{summary}"
    )


def deliver_summary_to_caller(
    herdr: str,
    summary: str,
    *,
    report_path: Path,
    notes_dir: Path,
    timeout_ms: int,
) -> None:
    """Send the finished-turn summary to the launcher agent in the parent session."""
    pane = load_launcher_pane(notes_dir)
    if not pane:
        print(
            "warning: no launcher pane saved; summary not delivered to caller",
            flush=True,
        )
        return
    try:
        target = resolve_agent_in_pane(herdr, pane)
    except RuntimeError as err:
        print(f"warning: cannot deliver summary to caller: {err}", flush=True)
        return
    text = launcher_summary_prompt(
        summary=summary, report_path=report_path, notes_dir=notes_dir
    )
    print(
        f"delivering summary to launcher agent {target} (pane {pane})",
        flush=True,
    )
    prompt_and_wait(herdr, target, text, timeout_ms=timeout_ms)


def persist_launcher_context(notes_dir: Path) -> None:
    """Save parent-pane identity for the daemon child (env can be stripped)."""
    ensure_notes_dir(notes_dir)
    pane = os.environ.get("HERDR_PANE_ID", "").strip()
    if pane:
        (notes_dir / "launcher-pane").write_text(pane + "\n", encoding="utf-8")
    env_flag = os.environ.get("HERDR_ENV", "").strip()
    if env_flag:
        (notes_dir / "launcher-herdr-env").write_text(env_flag + "\n", encoding="utf-8")


def load_launcher_pane(notes_dir: Path | None = None) -> str | None:
    pane = os.environ.get("HERDR_PANE_ID", "").strip()
    if pane:
        return pane
    if notes_dir is None:
        return None
    path = notes_dir / "launcher-pane"
    try:
        value = path.read_text(encoding="utf-8").strip()
    except OSError:
        return None
    return value or None


def daemonize(argv: list[str], *, notes_dir: Path) -> int:
    """Re-exec without --daemon; return immediately with pid/log JSON."""
    ensure_notes_dir(notes_dir)
    persist_launcher_context(notes_dir)
    log_path = notes_dir / "runner.log"
    child_argv = [a for a in argv if a != "--daemon"]
    # Ensure notes-dir is explicit for the child even if it was defaulted.
    if "--notes-dir" not in child_argv:
        child_argv.extend(["--notes-dir", str(notes_dir)])
    script = str(Path(__file__).resolve())
    cmd = [sys.executable, script, *child_argv]
    child_env = os.environ.copy()
    # Keep parent pane identity even if the child session is cleaned.
    pane = os.environ.get("HERDR_PANE_ID", "").strip()
    if pane:
        child_env["HERDR_PANE_ID"] = pane
    child_env["HERDR_ENV"] = os.environ.get("HERDR_ENV") or "1"
    log_f = open(log_path, "a", encoding="utf-8")  # noqa: SIM115 — kept by child
    try:
        proc = subprocess.Popen(
            cmd,
            stdin=subprocess.DEVNULL,
            stdout=log_f,
            stderr=subprocess.STDOUT,
            start_new_session=True,
            close_fds=True,
            env=child_env,
        )
    finally:
        log_f.close()
    print(
        json.dumps(
            {
                "ok": True,
                "pid": proc.pid,
                "log": str(log_path),
                "notes_dir": str(notes_dir),
                "message": (
                    "self-evolve runner started in background; "
                    "nested director/coder/reviewer (2x2) will start after idle grace"
                ),
            },
            ensure_ascii=False,
        )
    )
    return 0


def wait_until_idle(
    herdr: str,
    target: str,
    *,
    grace_ms: int,
    poll_seconds: float = DEFAULT_POLL_SECONDS,
    env: dict[str, str | None] | None = None,
) -> None:
    """Best-effort wait so a launcher agent can finish before first prompt."""
    if grace_ms <= 0:
        return
    deadline = time.monotonic() + (grace_ms / 1000.0)
    while time.monotonic() < deadline:
        try:
            status = agent_status(herdr, target, env=env)
        except RuntimeError:
            time.sleep(poll_seconds)
            continue
        if status in {"idle", "done"}:
            return
        time.sleep(poll_seconds)


