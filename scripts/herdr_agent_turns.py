def parse_verdict(review_text: str | None) -> str | None:
    if not review_text:
        return None
    match = VERDICT_RE.search(review_text)
    if match is None:
        return None
    return match.group(1).upper()


# Missing VERDICT: escalate only on clear owner/human-judgment signals
# (OWNER_ASK_RE); otherwise fall back to APPROVE for neutral reviews.
def resolve_review_verdict(review_text: str | None) -> tuple[str, list[str]]:
    """Return ``(verdict, notes)``; never silently APPROVE owner-ask text."""
    notes: list[str] = []
    explicit = parse_verdict(review_text)
    if explicit is not None:
        return explicit, notes
    if review_text and OWNER_ASK_RE.search(review_text):
        notes.append(
            "missing VERDICT line; owner-ask signal detected — treating as ESCALATE"
        )
        return "ESCALATE", notes
    notes.append("missing VERDICT line; treating as APPROVE")
    return "APPROVE", notes


def parse_plan_stop(plan_text: str | None) -> bool:
    if not plan_text:
        return False
    return STOP_PLAN_RE.search(plan_text) is not None


def parse_plan_stop_kind(plan_text: str | None) -> str | None:
    """Return ``DONE`` or ``STOP`` from planner STATUS/PLAN, else ``None``."""
    if not plan_text:
        return None
    match = STOP_PLAN_RE.search(plan_text)
    if match is None:
        return None
    return match.group(1).upper()


def parse_plan_escalate(plan_text: str | None) -> bool:
    if not plan_text:
        return False
    return PLAN_ESCALATE_RE.search(plan_text) is not None


def stop_text_implies_goal_met(*texts: str | None) -> bool:
    """True when STOP is accompanied by explicit goal-met language."""
    for text in texts:
        if text and GOAL_MET_STOP_RE.search(text):
            return True
    return False


def should_write_complete(
    *,
    final_verdict: str | None = None,
    plan_status: str | None = None,
    evidence_texts: tuple[str | None, ...] = (),
) -> bool:
    """Whether ``COMPLETE.md`` should be written for this stop.

    Write COMPLETE when:
    - review ``VERDICT: DONE``, or planner ``STATUS``/``PLAN: DONE``
    - review ``VERDICT: STOP`` or planner ``STATUS``/``PLAN: STOP`` **and**
      evidence text explicitly says the goal was met (``GOAL_MET_STOP_RE``)

    Do **not** write COMPLETE for ESCALATE, stall / repeated TASK,
    turn-cap-only exhaustion, or any ``NEEDS_OWNER.md`` path.
    COMPLETE and NEEDS_OWNER are mutually exclusive outcomes.
    """
    verdict = (final_verdict or "").strip().upper() or None
    plan = (plan_status or "").strip().upper() or None
    if verdict == "DONE" or plan == "DONE":
        return True
    if verdict == "STOP" or plan == "STOP":
        return stop_text_implies_goal_met(*evidence_texts)
    return False


