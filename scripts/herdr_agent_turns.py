def normalize_plan_task(text: str | None) -> str:
    """Normalize a PLAN TASK for stall comparison.

    Strip, lowercase, collapse whitespace, and trim trailing punctuation.
    """
    if not text:
        return ""
    cleaned = " ".join(text.strip().lower().split())
    return cleaned.rstrip(".,;:!?。、")


def plan_tasks_stall(
    current_plan: str | None, prev_plan: str | None
) -> bool:
    """True when both plans share the same normalized non-empty TASK.

    Intended for continuing plans only; DONE/STOP/ESCALATE current plans
    return False so existing early-exit handlers remain authoritative.
    """
    if not current_plan or not prev_plan:
        return False
    if parse_plan_stop(current_plan) or parse_plan_escalate(current_plan):
        return False
    current = normalize_plan_task(extract_labeled_field(current_plan, "TASK"))
    previous = normalize_plan_task(extract_labeled_field(prev_plan, "TASK"))
    return bool(current) and current == previous


