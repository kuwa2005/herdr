def escalate_why_excerpt(*texts: str | None, limit: int = 400) -> str:
    """Pick a short excerpt explaining why the loop escalated."""

    def _clip(value: str) -> str:
        value = value.strip()
        if len(value) > limit:
            return value[: limit - 1] + "…"
        return value

    for text in texts:
        if not text:
            continue
        for label in ("EFFECT", "IMPROVE", "REASON"):
            value = extract_labeled_field(text, label)
            if value and value.lower() not in {"none", "n/a", "-"}:
                return _clip(value)
        cleaned = summarize_body(text, limit=limit)
        if cleaned not in {"_(なし)_", "_(記載なし)_"}:
            return cleaned
        # Keep labeled lines as a last resort (summarize_body skips them).
        kept: list[str] = []
        for raw in text.splitlines():
            line = raw.strip()
            if not line or line.startswith("#") or line.startswith("_("):
                continue
            kept.append(line)
        if kept:
            return _clip(" ".join(kept))
    return "_(no detail)_"


